#!/usr/bin/env node
// Turn an OpenTTD savegame into a compact test fixture: base64 tile arrays.
// The port's tests compare generated maps against these, never against
// hand-written values.
//
// Usage: node fixture.mjs <save.sav> <out.json> --seed N [--rivers N]
//        [--landscape temperate] [--stages landscape] [--note text]
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { riffChunk, saveData } from './save.mjs';

const args = process.argv.slice(2);
const save = args[0];
const out = args[1];
if (!save || !out || !args.includes('--seed')) {
  console.error('usage: node fixture.mjs <save.sav> <out.json> --seed N [--rivers N] [--landscape temperate] [--stages landscape] [--note text]');
  process.exit(1);
}
const arg = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);

const { version, data } = saveData(save);
const chunk = (tag) => new Uint8Array(riffChunk(data, tag).payload);
const type = chunk('MAPT');
const height = chunk('MAPH');
const size = Math.round(Math.sqrt(type.length));
if (type.length !== size * size || height.length !== size * size) {
  throw new Error(`map chunks ${type.length}/${height.length} do not form a square map`);
}

const fixture = {
  note: arg('--note', 'OpenTTD 15.3 reference map, generated by re/openttd/tools/oracle.mjs'),
  seed: Number(arg('--seed')),
  mapSize: size,
  version,
  landscape: arg('--landscape', 'temperate'),
  amountOfRivers: Number(arg('--rivers', 0)),
  stages: arg('--stages', 'landscape'),
  saveSha256: createHash('sha256').update(readFileSync(save)).digest('hex'),
  height: Buffer.from(height).toString('base64'),
  type: Buffer.from(type).toString('base64'),
  m1: Buffer.from(chunk('MAPO')).toString('base64'),
  m3: Buffer.from(chunk('M3LO')).toString('base64'),
  m4: Buffer.from(chunk('M3HI')).toString('base64'),
  m5: Buffer.from(chunk('MAP5')).toString('base64'),
  m2: Buffer.from(chunk('MAP2')).toString('base64'),
};
writeFileSync(out, JSON.stringify(fixture));
console.log(`${out}: seed ${fixture.seed}, ${size}x${size}, rivers ${fixture.amountOfRivers}, ${fixture.landscape}`);
