#!/usr/bin/env node
// Generate the tree sprite layout tables from OpenTTD's src/table/tree_land.h.
// The tables are original data (GPL-2.0), not hand-written numbers.
// Usage: node tree-table.mjs [tree_land.h] [out.ts]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = process.argv[2] ?? join(here, '..', 'orig', 'openttd-15.3', 'src', 'table', 'tree_land.h');
const out = process.argv[3] ?? join(here, '..', '..', '..', 'web', 'games', 'openttd', 'src', 'render', 'treetable.ts');
const text = readFileSync(source, 'utf8');

const xyStart = text.indexOf('_tree_layout_xy');
const xyText = text.slice(xyStart, text.indexOf('};', xyStart));
const xy = [...xyText.matchAll(/\{\s*(\d+),\s*(\d+)\s*\}/g)].map((m) => [Number(m[1]), Number(m[2])]);
if (xy.length !== 16) throw new Error(`expected 16 tree positions, found ${xy.length}`);

const sStart = text.indexOf('_tree_layout_sprite');
const sText = text.slice(sStart, text.indexOf('\n};', sStart));
const rows = [];
for (const line of sText.split('\n')) {
  const m = line.match(/^\s*\{\s*(\{.*\})\s*\},?\s*\/\/\s*(\d+)/);
  if (!m) continue;
  const ids = [...m[1].matchAll(/\{\s*(0x[0-9a-fA-F]+|\d+)\s*,\s*([A-Z_0-9]+)\s*\}/g)]
    .map((x) => [Number(x[1]), x[2]]);
  if (ids.length !== 4) throw new Error(`row ${m[2]} has ${ids.length} sprites`);
  rows.push(ids);
}
if (rows.length !== 196) throw new Error(`bad table: ${rows.length} rows`);

const body = `// Generated by re/openttd/tools/tree-table.mjs from
// src/table/tree_land.h of OpenTTD 15.3 (GPL-2.0). Do not edit by hand.

/** _tree_layout_xy: the four tree positions within a tile, for each tile hash. */
export const TREE_LAYOUT_XY: readonly (readonly (readonly [number, number])[])[] = ${JSON.stringify(
  Array.from({ length: 4 }, (_, i) => xy.slice(i * 4, i * 4 + 4)),
)};

/** _tree_layout_sprite: base sprite and palette per tree type and sub-position. */
export const TREE_LAYOUT_SPRITE: readonly (readonly (readonly [number, string])[])[] = [
${rows.map((r) => `  [${r.map((x) => `[${x[0]}, '${x[1]}']`).join(', ')}],`).join('\n')}
];
`;
writeFileSync(out, body);
console.log(`${out}: ${rows.length} rows, ${xy.length} positions`);
