"""Writes web/games/teeworlds/src/client/engine/keys.ts from the release's src/engine/keys.h (the key enum)
and src/engine/client/keynames.h (g_aaKeyStrings), unchanged in content. Run: python3 -I keys.py"""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'orig', 'teeworlds-0.7.5-src', 'src', 'engine')
out = os.path.join(here, '..', '..', '..', 'web', 'games', 'teeworlds', 'src', 'client', 'engine', 'keys.ts')

keys = re.findall(r'\b(KEY_[A-Z0-9_]+)\s*=\s*(\d+)', open(os.path.join(src, 'keys.h')).read())
body = open(os.path.join(src, 'client', 'keynames.h')).read()
names = re.findall(r'"((?:[^"\\]|\\.)*)"', body[body.index('{'):])
assert len(names) == 512, len(names)

lines = [
    '// (c) Magnus Auvinen. See licence.txt in the root of the distribution for more information.',
    '// If you are missing that file, acquire a complete release at teeworlds.com.',
    '// Generated by re/teeworlds/tools/keys.py from engine/keys.h and engine/client/keynames.h of Teeworlds 0.7.5',
    '// (altered: TypeScript). Do not edit.',
    '',
]
last = 0
for name, value in keys:
    lines.append(f'export const {name} = {value};')
    last = int(value)
lines.append(f'export const KEY_LAST = {last + 1};')
lines.append('export const g_MaxKeys = 512;')
lines.append('export const g_aaKeyStrings: string[] = [')
for i in range(0, 512, 8):
    lines.append('  ' + ' '.join(f'"{n}",' for n in names[i:i + 8]))
lines.append('];')
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote', out)
