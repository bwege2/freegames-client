def java_maps():
    """the official maps (datasrc/maps), unchanged, for the server (it loads them and sends them to clients)"""
    import base64
    d = os.path.join(datasrc, 'maps')
    names = sorted(n[:-4] for n in os.listdir(d) if n.endswith('.map'))
    L = ['/*'] + [' * ' + l for l in HEADER.split('\n')] + [' */']
    L += ['package %s;' % JAVA_PKG, '',
          '/**', ' * The official maps of Teeworlds 0.7.5 (datasrc/maps/*.map), byte for byte, base64 encoded:',
          ' * CC BY-SA 3.0, Copyright (c) 2015 Magnus Auvinen (web/games/teeworlds/LICENSE.md).', ' */',
          'public final class Maps {', '  private Maps() {}', '',
          '  /** the names of the official maps */',
          '  public static final String[] NAMES = {%s};' % ', '.join('"%s"' % n for n in names), '',
          '  /** the map file, or null */',
          '  public static byte[] get(String name) {',
          '    String[] parts;',
          '    switch (name) {']
    for n in names:
        L.append('      case "%s": parts = %s(); break;' % (n, 'm_' + n))
    L += ['      default: return null;', '    }',
          '    StringBuilder sb = new StringBuilder();', '    for (String p : parts) sb.append(p);',
          '    return java.util.Base64.getDecoder().decode(sb.toString());', '  }', '']
    for n in names:
        data = base64.b64encode(open(os.path.join(d, n + '.map'), 'rb').read()).decode('ascii')
        chunks = [data[i:i + 16000] for i in range(0, len(data), 16000)]
        L.append('  private static String[] m_%s() {' % n)
        L.append('    return new String[] {')
        for c in chunks:
            L.append('      "%s",' % c)
        L.append('    };')
        L.append('  }')
    L.append('}')
    L.append('')
    return '\n'.join(L)

