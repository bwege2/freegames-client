def fmt_float(v):
    return '%f' % v   # as datatypes.Float emits it ("%ff")

def structs_in_order():
    order = []
    for line in open(os.path.join(datasrc, 'content.py'), encoding='utf8'):
        line = line.strip()
        if line.startswith('class ') and '(Struct)' in line:
            order.append(line.split()[1].split('(')[0])
    return order

def member_name(var, name):
    return dt.FormatName(var.TypeName(), name)

def ts_content():
    order = structs_in_order()
    L = ['// ' + l for l in HEADER.split('\n')]
    L += ['// The data container (client_data.cpp / server_data.cpp): images, sprites, animations, sounds, weapons.', '']
    # interfaces
    for cname in order:
        inst = content.__dict__[cname]()
        L.append('export interface %s {' % inst.TypeName())
        for m in inst.Members():
            v = m.var
            if isinstance(v, dt.Array):
                L.append('  m_Num%s: number;' % dt.FixCasing(m.name))
                L.append('  %s: %s[];' % (dt.FormatName('[]', m.name), ts_type(v.type)))
            else:
                L.append('  %s: %s;' % (member_name(v, m.name), ts_type(v)))
        L.append('}')
    L.append('')
    paths = {}
    def walk(v, path):
        if isinstance(v, dt.Struct):
            paths[id(v)] = path
            for m in v.Members():
                mv = m.var
                if isinstance(mv, dt.Array):
                    for i, it in enumerate(mv.items):
                        walk(it, '%s.%s[%d]' % (path, dt.FormatName('[]', m.name), i))
                else:
                    walk(mv, '%s.%s' % (path, member_name(mv, m.name)))
    walk(content.container, 'g_pData')
    fixups = []
    def lit(v, path):
        if isinstance(v, dt.Struct):
            parts = []
            for m in v.Members():
                mv = m.var
                if isinstance(mv, dt.Array):
                    items = [lit(it, '%s.%s[%d]' % (path, dt.FormatName('[]', m.name), i)) for i, it in enumerate(mv.items)]
                    parts.append('m_Num%s: %d' % (dt.FixCasing(m.name), len(mv.items)))
                    parts.append('%s: [%s]' % (dt.FormatName('[]', m.name), ', '.join(items)))
                else:
                    parts.append('%s: %s' % (member_name(mv, m.name), lit(mv, '%s.%s' % (path, member_name(mv, m.name)))))
            return '{ ' + ', '.join(parts) + ' }'
        if isinstance(v, dt.Pointer):
            t = v.target
            if t is not None and id(t) in paths:
                fixups.append('%s = %s;' % (path, paths[id(t)]))
                return 'null!'
            if t is None:
                return 'null!'
            return lit(t, path + '$')
        if isinstance(v, dt.Int):
            return str(v.value)
        if isinstance(v, dt.Float):
            return 'Math.fround(%s)' % fmt_float(v.value)
        if isinstance(v, dt.String):
            return '"%s"' % v.value
        if isinstance(v, (dt.TextureHandle, dt.SampleHandle)):
            return '-1'
        raise TypeError(v)
    body = lit(content.container, 'g_pData')
    L.append('export const g_pData: CDataContainer = %s;' % body)
    L += fixups
    L.append('')
    images = [i.name.value.upper() for i in content.container.images.items]
    anims = [i.name.value.upper() for i in content.container.animations.items]
    sprites = [i.name.value.upper() for i in content.container.sprites.items]
    for prefix, names, num in (('IMAGE_', images, 'NUM_IMAGES'), ('ANIM_', anims, 'NUM_ANIMS'), ('SPRITE_', sprites, 'NUM_SPRITES')):
        for i, n in enumerate(names):
            L.append('export const %s%s = %d;' % (prefix, n, i))
        L.append('export const %s = %d;' % (num, len(names)))
    L.append('')
    return '\n'.join(L)

def ts_type(v):
    if isinstance(v, dt.Int):
        return 'number'
    if isinstance(v, dt.Float):
        return 'number'
    if isinstance(v, dt.String):
        return 'string'
    if isinstance(v, (dt.TextureHandle, dt.SampleHandle)):
        return 'number'
    if isinstance(v, dt.Pointer):
        return v.TypeName().rstrip('*')
    if isinstance(v, dt.Struct):
        return v.TypeName()
    raise TypeError(v)

