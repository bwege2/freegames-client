CFG = {'CFGFLAG_SAVE': 1, 'CFGFLAG_CLIENT': 2, 'CFGFLAG_SERVER': 4, 'CFGFLAG_STORE': 8, 'CFGFLAG_MASTER': 16, 'CFGFLAG_ECON': 32,
       'CFGFLAG_BASICACCESS': 64}

def config_vars():
    """the release build's variables, in the order the config manager registers them"""
    src = os.path.join(datasrc, '..', 'src')
    out = []
    def read(path):
        skip = 0
        for line in open(path, encoding='utf8'):
            s = line.strip()
            if s.startswith('#ifdef CONF_DEBUG'):
                skip = 1
                continue
            if skip and s.startswith('#endif'):
                skip = 0
                continue
            if skip:
                continue
            if s.startswith('#include') and 'variables.h' in s:
                read(os.path.join(src, 'game', 'variables.h'))
                continue
            if not s.startswith('MACRO_CONFIG_'):
                continue
            kind = 'int' if s.startswith('MACRO_CONFIG_INT') else 'str'
            body = s[s.index('(') + 1:s.rindex(')')]
            args, cur, q = [], '', False
            for ch in body:
                if ch == '"':
                    q = not q
                if ch == ',' and not q:
                    args.append(cur.strip())
                    cur = ''
                else:
                    cur += ch
            args.append(cur.strip())
            def num(e):
                e = e.strip()
                if e in ('MAX_CLIENTS',):
                    return 64
                if e == 'MAX_PLAYERS':
                    return 16
                if e == 'SERVERINFO_LEVEL_MIN':
                    return 0
                if e == 'SERVERINFO_LEVEL_MAX':
                    return 2
                v = int(e, 0)
                return v - (1 << 32) if v >= 1 << 31 else v
            flags = sum(CFG[f.strip()] for f in args[-2].split('|'))
            if kind == 'int':
                out.append({'kind': kind, 'name': args[0], 'script': args[1], 'def': num(args[2]), 'min': num(args[3]),
                            'max': num(args[4]), 'flags': flags, 'desc': args[-1]})
            else:
                out.append({'kind': kind, 'name': args[0], 'script': args[1], 'len': num(args[2]), 'def': args[3],
                            'flags': flags, 'desc': args[-1]})
    read(os.path.join(src, 'engine', 'shared', 'config_variables.h'))
    return out

