def evalc(expr):
    expr = str(expr)
    try:
        return int(expr)
    except ValueError:
        pass
    for op in ('-', '+'):
        if op in expr[1:]:
            a, b = expr.rsplit(op, 1)
            return evalc(a) - evalc(b) if op == '-' else evalc(a) + evalc(b)
    return cvalue[expr]

# ------------------------------------------------------------------ net objects, events, messages
def flatten(variables):
    """[(kind, name, args)] per int of the struct, in order; kind: int, range, flag, string, stringstrict"""
    out = []
    for v in variables:
        if isinstance(v, dt.NetArray):
            inner = v.var
            if isinstance(inner, dt.NetArray):  # 2-d (m_aaSkinPartNames)
                for i in range(v.size):
                    for j in range(inner.size):
                        out.append(one(inner.var, '%s[%d][%d]' % (inner.base_name, i, j), (inner.base_name, i * inner.size + j)))
            else:
                for i in range(v.size):
                    out.append(one(inner, '%s[%d]' % (v.base_name, i), (v.base_name, i)))
        else:
            out.append(one(v, v.name, None))
    return out

def one(v, cname, arr):
    if isinstance(v, dt.NetFlag):
        kind, args = 'flag', (v.mask,)
    elif isinstance(v, dt.NetIntRange):
        kind, args = 'range', (v.min, v.max)
    elif isinstance(v, dt.NetStringStrict):
        kind, args = 'stringstrict', ()
    elif isinstance(v, dt.NetString):
        kind, args = 'string', ()
    elif isinstance(v, dt.NetIntAny):
        kind, args = 'int', ()
    else:
        raise TypeError(v)
    return {'kind': kind, 'cname': cname, 'arr': arr, 'args': args, 'default': getattr(v, 'default', None)}

def mask_value(mask):
    if mask == '0':
        return 0
    return sum(cvalue[m] for m in mask.split('|'))

