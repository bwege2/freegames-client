def members(fields):
    """struct members: (name, count) in order (arrays collapse)"""
    out = []
    for f in fields:
        if f['arr']:
            name = f['arr'][0]
            if out and out[-1][0] == name:
                out[-1] = (name, out[-1][1] + 1)
                continue
            out.append((name, 1))
        else:
            out.append((f['cname'], 0))
    return out

# ------------------------------------------------------------------ TypeScript
def ts_protocol():
    L = ['// ' + l for l in HEADER.split('\n')]
    L += ['// The game protocol: engine/shared/protocol.h is in ../engine/shared/protocol.ts.', '']
    L += ['import { CUnpacker, CMsgPacker, SANITIZE_CC, SKIP_START_WHITESPACES } from \'../engine/shared/packer.ts\';', '']
    for n, v in consts:
        L.append('export const %s = %d;' % (n, v))
    L.append('')
    # objects
    for name, d in objs.items():
        o = d['o']
        ext = (' extends %s' % d['base']['o'].struct_name) if d['base'] else ''
        L.append('export interface %s%s {' % (o.struct_name, ext))
        for m, c in members(d['own']):
            L.append('  %s: number%s;' % (m, '[]' if c else ''))
        L.append('}')
        n = len(d['fields'])
        L.append('export const %s_SIZE = %d; // ints' % (o.struct_name, n))
        L.append('export function read_%s(d: Int32Array, o = 0): %s {' % (o.struct_name, o.struct_name))
        L.append('  return {')
        i = 0
        for m, c in members(d['fields']):
            if c:
                L.append('    %s: [%s],' % (m, ', '.join('d[o + %d]' % (i + k) for k in range(c))))
                i += c
            else:
                L.append('    %s: d[o + %d],' % (m, i))
                i += 1
        L.append('  };')
        L.append('}')
        L.append('export function write_%s(s: %s, d: Int32Array, o = 0): void {' % (o.struct_name, o.struct_name))
        i = 0
        for m, c in members(d['fields']):
            if c:
                for k in range(c):
                    L.append('  d[o + %d] = s.%s[%d];' % (i, m, k))
                    i += 1
            else:
                L.append('  d[o + %d] = s.%s;' % (i, m))
                i += 1
        L.append('}')
        L.append('')
    L.append('export const g_apObjNames = ["invalid", %s, ""];' % ', '.join('"%s"' % o.name for o in network.Objects))
    L.append('/** sizeof(CNetObj_*) in bytes, as ms_aObjSizes */')
    L.append('export const g_aObjSizes = [0, %s, 0];' % ', '.join(str(4 * len(objs[o.name]['fields'])) for o in network.Objects))
    L.append('export const g_apMsgNames = ["invalid", %s, ""];' % ', '.join('"%s"' % o.name for o in network.Messages))
    L.append('')
    # messages
    for o in network.Messages:
        fl = flatten(o.variables)
        L.append('export interface %s {' % o.struct_name)
        for m, c in members(fl):
            isstr = any(f['kind'].startswith('string') for f in fl if (f['arr'] and f['arr'][0] == m) or f['cname'] == m)
            t = 'string' if isstr else 'number'
            L.append('  %s: %s%s;' % (m, t, '[]' if c else ''))
        L.append('}')
        L.append('export function pack_%s(%s: %s, p: CMsgPacker): boolean {' % (o.struct_name, 'm' if fl else '_m', o.struct_name))
        for f in fl:
            ref = 'm.' + (f['arr'][0] + '[%d]' % f['arr'][1] if f['arr'] else f['cname'])
            if f['kind'].startswith('string'):
                L.append('  p.AddString(%s, -1);' % ref)
            else:
                L.append('  p.AddInt(%s);' % ref)
        L.append('  return p.Error();')
        L.append('}')
        L.append('')
    # the handler
    L += ['/** CNetObjHandler (generated/protocol.cpp): validation of snapshot objects, secure unpacking of messages */',
          'export class CNetObjHandler {',
          '  private m_pMsgFailedOn: string | null = "";',
          '  private m_pObjFailedOn: string | null = "";',
          '  private m_NumObjFailures = 0;',
          '  private CheckInt(pErrorMsg: string, Value: number, Min: number, Max: number): boolean {',
          '    if (Value < Min || Value > Max) { this.m_pObjFailedOn = pErrorMsg; this.m_NumObjFailures++; return false; }',
          '    return true;',
          '  }',
          '  private CheckFlag(pErrorMsg: string, Value: number, Mask: number): boolean {',
          '    if ((Value & Mask) !== Value) { this.m_pObjFailedOn = pErrorMsg; this.m_NumObjFailures++; return false; }',
          '    return true;',
          '  }',
          '  FailedObjOn(): string | null { return this.m_pObjFailedOn; }',
          '  NumObjFailures(): number { return this.m_NumObjFailures; }',
          '  FailedMsgOn(): string | null { return this.m_pMsgFailedOn; }',
          '  GetObjName(Type: number): string { if (Type < 0 || Type >= NUM_NETOBJTYPES) return "(out of range)"; return g_apObjNames[Type]; }',
          '  GetObjSize(Type: number): number { if (Type < 0 || Type >= NUM_NETOBJTYPES) return 0; return g_aObjSizes[Type]; }',
          '  GetMsgName(Type: number): string { if (Type < 0 || Type >= NUM_NETMSGTYPES) return "(out of range)"; return g_apMsgNames[Type]; }',
          '  /** Size in bytes; pData: the item\'s ints */',
          '  ValidateObj(Type: number, pData: Int32Array, Size: number): number {',
          '    const d = pData;',
          '    switch (Type) {']
    for name, d in objs.items():
        o = d['o']
        L.append('      case %s: {' % o.enum_name)
        L.append('        if (%d !== Size) return -1;' % (4 * len(d['fields'])))
        # datasrc/compile.py validates an object's own variables only (not its base's: CNetObj_Character
        # carries m_HookedPlayer -1, out of CharacterCore's range, and is valid)
        for i, f in enumerate(d['fields']):
            if i < len(d['fields']) - len(d['own']):
                continue
            nm = f['cname']
            if f['kind'] == 'range':
                L.append('        if (!this.CheckInt("%s", d[%d], %d, %d)) return -1;' % (nm, i, evalc(f['args'][0]), evalc(f['args'][1])))
            elif f['kind'] == 'flag':
                L.append('        if (!this.CheckFlag("%s", d[%d], %d)) return -1;' % (nm, i, mask_value(f['args'][0])))
        L.append('        return 0;')
        L.append('      }')
    L += ['    }', '    return -1;', '  }', '',
          '  /** the message, or null (FailedMsgOn() says why) */',
          '  SecureUnpackMsg(Type: number, pUnpacker: CUnpacker): object | null {',
          '    this.m_pMsgFailedOn = null;',
          '    this.m_pObjFailedOn = null;',
          '    let pMsg: Record<string, unknown> | null = null;',
          '    switch (Type) {']
    for o in network.Messages:
        fl = flatten(o.variables)
        L.append('      case %s: {' % o.enum_name)
        init = []
        for m, c in members(fl):
            isstr = any(f['kind'].startswith('string') for f in fl if (f['arr'] and f['arr'][0] == m) or f['cname'] == m)
            init.append('%s: %s' % (m, ('[]' if c else ('""' if isstr else '0'))))
        L.append('        const m: Record<string, any> = { %s };' % ', '.join(init))
        L.append('        pMsg = m;')
        for f in fl:
            ref = 'm.' + (f['arr'][0] + '[%d]' % f['arr'][1] if f['arr'] else f['cname'])
            if f['kind'] == 'string':
                L.append('        %s = pUnpacker.GetString();' % ref)
            elif f['kind'] == 'stringstrict':
                L.append('        %s = pUnpacker.GetString(SANITIZE_CC | SKIP_START_WHITESPACES);' % ref)
            elif f['default'] is not None:
                L.append('        %s = pUnpacker.GetIntOrDefault(%s);' % (ref, f['default']))
            else:
                L.append('        %s = pUnpacker.GetInt();' % ref)
        checks = []
        for f in fl:
            ref = 'm.' + (f['arr'][0] + '[%d]' % f['arr'][1] if f['arr'] else f['cname'])
            if f['kind'] == 'range':
                checks.append('this.CheckInt("%s", %s, %d, %d)' % (f['cname'], ref, evalc(f['args'][0]), evalc(f['args'][1])))
            elif f['kind'] == 'flag':
                checks.append('this.CheckFlag("%s", %s, %d)' % (f['cname'], ref, mask_value(f['args'][0])))
        if checks:
            L.append('        void (%s);' % ' && '.join(checks))
        L.append('        break;')
        L.append('      }')
    L += ['      default:',
          '        this.m_pMsgFailedOn = "(type out of range)";',
          '        break;',
          '    }',
          '    if (pUnpacker.Error()) this.m_pMsgFailedOn = "(unpack error)";',
          '    if (this.m_pMsgFailedOn !== null || this.m_pObjFailedOn !== null) {',
          '      if (this.m_pMsgFailedOn === null) this.m_pMsgFailedOn = "";',
          '      if (this.m_pObjFailedOn === null) this.m_pObjFailedOn = "";',
          '      return null;',
          '    }',
          '    this.m_pMsgFailedOn = "";',
          '    this.m_pObjFailedOn = "";',
          '    return pMsg;',
          '  }',
          '}', '']
    return '\n'.join(L)

