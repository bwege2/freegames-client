# check them against the raw header (the enum's values follow C's counting)
def raw_check():
    names = {}
    for block in network.RawHeader.split('enum')[1:]:
        body = block.split('{', 1)[1].split('}', 1)[0]
        val = -1
        for item in body.split(','):
            item = item.strip()
            if not item:
                continue
            if '=' in item:
                n, v = [s.strip() for s in item.split('=')]
                val = int(v, 0)
            else:
                n = item
                val += 1
            names[n] = val
    for n, v in RAW:
        assert names.get(n) == v, (n, names.get(n), v)
    assert len(names) == len(RAW), sorted(set(names) - {n for n, _ in RAW})
