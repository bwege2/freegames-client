# Writes msgdump.cpp for the server oracle's scripted clients: one function that prints a game message
# unpacked by the original CNetObjHandler::SecureUnpackMsg as a JSON object, field by field, generated
# from the original's datasrc/network.py (the same definitions compile.py turns into protocol.h).
#   python3 -I gen_msgdump.py <teeworlds-src> > msgdump.cpp
import sys
sys.path.insert(0, sys.argv[1] + "/datasrc")
import network
from datatypes import NetArray, NetString, NetStringStrict

def fields(v):
    if isinstance(v, NetArray):
        out = []
        for i in range(v.size):
            inner = v.var
            base = v.base_name
            kind = "s" if isinstance(inner, (NetString, NetStringStrict)) else "i"
            out.append(("%s[%d]" % (base, i), kind))
        return out
    return [(v.name, "s" if isinstance(v, (NetString, NetStringStrict)) else "i")]

print('// generated by gen_msgdump.py from datasrc/network.py: do not edit')
print('#include <base/system.h>')
print('#include <engine/shared/protocol.h>')
print('#include <generated/protocol.h>')
print('#include <string>')
print('void JsonStr(std::string &o, const char *s);')
print('void MsgDump(std::string &o, int Type, const void *pRaw)')
print('{')
print('\tchar b[64];')
print('\tswitch(Type)')
print('\t{')
for m in network.Messages:
    print('\tcase %s: {' % m.enum_name)
    print('\t\tconst %s *p = (const %s *)pRaw; (void)p;' % (m.struct_name, m.struct_name))
    print('\t\to += "{\\"t\\":\\"%s\\"";' % m.name)
    for var in m.variables:
        for name, kind in fields(var):
            key = name.replace('[', '_').replace(']', '')
            if kind == 's':
                print('\t\to += ",\\"%s\\":"; JsonStr(o, p->%s);' % (key, name))
            else:
                print('\t\tstr_format(b, sizeof(b), ",\\"%s\\":%%d", p->%s); o += b;' % (key, name))
    print('\t\to += "}";')
    print('\t} break;')
print('\tdefault: str_format(b, sizeof(b), "{\\"t\\":%d}", Type); o += b;')
print('\t}')
print('}')
