#!/usr/bin/env python3
"""Writes web/games/abuse/src/fontdata.ts from the original's font bitmaps.

smallfnt.cpp (small_font) and fnt6x13.cpp (fnt6x13) are byte arrays written by Satan Paint:
`unsigned char name[W*H]={ ... };`. The arrays keep their C names and sizes; an initializer
shorter than the declared size is padded with zeros, as C does.

Usage: python3 re/abuse/tools/fontdata.py   (from the worktree root, or anywhere)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
SRC = os.path.join(ROOT, 're', 'abuse', 'orig', 'abuse-0.8', 'src')
OUT = os.path.join(ROOT, 'web', 'games', 'abuse', 'src', 'fontdata.ts')

DECL = re.compile(r'unsigned\s+char\s+(\w+)\s*\[\s*([0-9*\s]+)\]\s*=\s*\{(.*?)\}\s*;', re.S)


def size_of(expr):
    n = 1
    for f in expr.split('*'):
        n *= int(f.strip())
    return n


def parse(path):
    text = open(path, encoding='latin-1').read()
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    text = re.sub(r'//[^\n]*', '', text)
    m = DECL.search(text)
    if not m:
        sys.exit(f'{path}: no array found')
    name, size = m.group(1), size_of(m.group(2))
    vals = [int(v, 0) & 0xff for v in m.group(3).replace('\n', ' ').split(',') if v.strip()]
    if len(vals) > size:
        sys.exit(f'{path}: {len(vals)} values for {size} bytes')
    vals += [0] * (size - len(vals))
    return name, m.group(2).strip(), vals


def emit(name, dims, vals):
    lines = [f'/** {os.path.basename(name)}[{dims}] */', f'export const {name} = Uint8Array.from([']
    for i in range(0, len(vals), 32):
        lines.append('  ' + ', '.join(str(v) for v in vals[i:i + 32]) + ',')
    lines.append(']);')
    return '\n'.join(lines)


def main():
    parts = ['// smallfnt.cpp, fnt6x13.cpp: the built-in font bitmaps (one byte per pixel).',
             '// Generated by re/abuse/tools/fontdata.py from the original source; do not edit.', '']
    for f in ('smallfnt.cpp', 'fnt6x13.cpp'):
        name, dims, vals = parse(os.path.join(SRC, f))
        parts.append(emit(name, dims, vals))
        parts.append('')
    with open(OUT, 'w') as fp:
        fp.write('\n'.join(parts))
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
