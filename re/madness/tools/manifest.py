#!/usr/bin/env python3
"""Write web/games/madness/ASSET-MANIFEST.csv: every file the port ships from the game's assets, with its
size, SHA-256, where it comes from and its licence. `fetch.sh` copies the files from MIR 0.51.1-beta
(commit 8d2da4dd5ecd041884ba7cc57ab1ba1e09c73d0e) and replaces the two non-free fonts; this script records
what the port actually ships. Run it from re/madness: `python3 -I tools/manifest.py`."""
import csv
import hashlib
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(HERE, '..', '..', 'web', 'games', 'madness', 'assets')
OUT = os.path.join(HERE, '..', '..', 'web', 'games', 'madness', 'ASSET-MANIFEST.csv')
MIR = 'Madness Interactive Reloaded 0.51.1-beta (commit 8d2da4d), base/'
OFL = 'SIL Open Font License 1.1'
GF = 'https://github.com/google/fonts/tree/main/ofl'

# the files the port does not copy unchanged from MIR's base/ folder
SPECIAL = {
    'fonts/impact.wf': (
        'generated by re/madness/tools/make-wf.py from Anton-Regular.ttf (sha256 '
        'a4ba3a92350ebb031da0cb47630ac49eb265082ca1bc0450442f4a83ab947cab), ' + GF + '/anton', OFL),
    'fonts/toxigenesis.wf': (
        'generated by re/madness/tools/make-wf.py from RussoOne-Regular.ttf (sha256 '
        'bc0abcc660bd8b7ad3000ecb2898a27c58a29a50f7ec81652fa12e75148d09df), ' + GF + '/russoone', OFL),
    'fonts/OFL-Anton.txt': ('copied from ' + GF + '/anton/OFL.txt', OFL),
    'fonts/OFL-Inter.txt': ('copied from ' + GF + '/inter/OFL.txt', OFL),
    'fonts/OFL-Oxanium.txt': ('copied from ' + GF + '/oxanium/OFL.txt', OFL),
    'fonts/OFL-RussoOne.txt': ('copied from ' + GF + '/russoone/OFL.txt', OFL),
}


def main() -> None:
    rows = []
    for root, dirs, files in os.walk(ASSETS):
        dirs.sort()
        for name in sorted(files):
            path = os.path.join(root, name)
            rel = os.path.relpath(path, ASSETS).replace(os.sep, '/')
            if rel == 'ASSET-MANIFEST.csv':
                continue
            with open(path, 'rb') as f:
                data = f.read()
            if rel in SPECIAL:
                source, licence = SPECIAL[rel]
            else:
                source, licence = MIR + rel, 'GPL-3.0'
            rows.append((rel, len(data), hashlib.sha256(data).hexdigest(), source, licence))
    rows.sort()
    with open(OUT, 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerow(['path', 'bytes', 'sha256', 'source', 'licence'])
        w.writerows(rows)
    print(f'wrote {OUT}: {len(rows)} files')


if __name__ == '__main__':
    main()
