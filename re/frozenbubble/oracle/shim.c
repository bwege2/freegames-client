static void init_channels(void)
{
	int i;
	if (chan_init) return;
	for (i = 0; i < 4096; i++) chan_volume[i] = MIX_MAX_VOLUME;
	chan_init = 1;
}

/* the model's audio "callback": fades end at their virtual time */
static void music_update(void)
{
	if (!music_cur) return;
	if (music_fading != MIX_NO_FADING && vt >= music_fade_end) {
		if (music_fading == MIX_FADING_OUT) {
			music_cur = NULL;
			tr("M %llu stopped\n", (unsigned long long)music_fade_end);
		}
		music_fading = MIX_NO_FADING;
	}
}

int Mix_OpenAudio(int frequency, Uint16 format, int channels, int chunksize)
{
	init_channels();
	tr("A %llu open %d %u %d %d\n", (unsigned long long)vt, frequency, format, channels, chunksize);
	audio_open = 1; audio_freq = frequency; audio_format = format; audio_channels = channels;
	return 0;
}

void Mix_CloseAudio(void)
{
	tr("A %llu close\n", (unsigned long long)vt);
	audio_open = 0;
}

int Mix_QuerySpec(int *frequency, Uint16 *format, int *channels)
{
	if (frequency) *frequency = audio_freq;
	if (format) *format = audio_format;
	if (channels) *channels = audio_channels;
	return audio_open;
}

int Mix_AllocateChannels(int n)
{
	if (n >= 0 && n != nchannels) {
		tr("A %llu allocate %d\n", (unsigned long long)vt, n);
		nchannels = n > 4096 ? 4096 : n;
	}
	return nchannels;
}

int Mix_ReserveChannels(int n) { return n > nchannels ? nchannels : n; }

Mix_Chunk *Mix_LoadWAV_RW(SDL_RWops *src, int freesrc)
{
	fchunk *c;
	int i;
	if (!src) return NULL;
	c = calloc(1, sizeof *c);
	c->c.allocated = 1;
	c->c.volume = MIX_MAX_VOLUME;
	strcpy(c->name, "?");
	for (i = 0; i < 16; i++)
		if (rwnames[i].rw == src) { strcpy(c->name, rwnames[i].name); rwnames[i].rw = NULL; }
	if (freesrc) SDL_RWclose(src);
	return &c->c;
}

