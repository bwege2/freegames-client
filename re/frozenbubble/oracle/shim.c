int Mix_FadeInMusicPos(Mix_Music *mm, int loops, int ms, double pos)
{
	fmusic *m = (fmusic *)mm;
	if (!audio_open) { SDL_SetError("Audio device hasn't been opened"); return -1; }
	if (!m) { SDL_SetError("music parameter was NULL"); return -1; }
	music_update();
	/* SDL_mixer 1.2.12: wait (SDL_Delay(100) steps) for a fade-out to end */
	while (music_cur && music_fading == MIX_FADING_OUT) { SDL_Delay(100); music_update(); }
	if (ms) tr("M %llu fadein %s %d %d %g\n", (unsigned long long)vt, m->name, loops, ms, pos);
	else tr("M %llu play %s %d\n", (unsigned long long)vt, m->name, loops);
	music_cur = m;
	music_paused = 0;
	music_fading = ms ? MIX_FADING_IN : MIX_NO_FADING;
	music_fade_end = vt + (uint64_t)ms;
	return 0;
}

int Mix_FadeInMusic(Mix_Music *m, int loops, int ms) { return Mix_FadeInMusicPos(m, loops, ms, 0.0); }
int Mix_PlayMusic(Mix_Music *m, int loops) { return Mix_FadeInMusicPos(m, loops, 0, 0.0); }

int Mix_FadeOutMusic(int ms)
{
	music_update();
	if (!music_cur) return 0;
	if (ms <= 0) { Mix_HaltMusic(); return 1; }
	tr("M %llu fadeout %d\n", (unsigned long long)vt, ms);
	if (music_fading != MIX_FADING_OUT) {
		music_fading = MIX_FADING_OUT;
		music_fade_end = vt + (uint64_t)ms;
	}
	return 1;
}

int Mix_HaltMusic(void)
{
	music_update();
	tr("M %llu halt\n", (unsigned long long)vt);
	music_cur = NULL;
	music_fading = MIX_NO_FADING;
	return 0;
}

