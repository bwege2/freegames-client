void exit(int status)
{
	typedef void (*exit_fn)(int);
	static exit_fn real;
	tr("X %llu exit %d\n", (unsigned long long)vt, status);
	if (trace) fflush(trace);
	if (!real) real = (exit_fn)dlsym(RTLD_NEXT, "exit");
	real(status);
	for (;;) ;
}

void _exit(int status)
{
	tr("X %llu exit %d\n", (unsigned long long)vt, status);
	die_exit(status);
	for (;;) ;
}

__attribute__((constructor)) static void fbshim_init(void)
{
	const char *s = getenv("ORACLE_SESSION"), *t = getenv("ORACLE_TRACE"), *fr = getenv("ORACLE_FRAMES");
	main_thread = pthread_self();
	/* only the game's perl process traces (not `timeout`, nor children such as bzip2 or mv) */
	if (strcmp(program_invocation_short_name, "perl") != 0) return;
	if (t) {
		trace = fopen(t, "w");
		if (!trace) { fprintf(stderr, "fbshim: cannot write %s\n", t); die_exit(3); }
		setvbuf(trace, NULL, _IOFBF, 1 << 16);
	}
	/* frames only when the directory exists (run.sh always passes the same variable) */
	if (fr && *fr) {
		struct stat st;
		if (stat(fr, &st) == 0 && S_ISDIR(st.st_mode)) snprintf(frames_dir, sizeof frames_dir, "%s", fr);
	}
	if (s) load_session(s);
}

