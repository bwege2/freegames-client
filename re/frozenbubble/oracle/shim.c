static uint32_t crc_table[256];
static uint32_t crc(uint32_t c, const unsigned char *p, size_t n)
{
	size_t i;
	if (!crc_table[1]) {
		uint32_t k, j, v;
		for (k = 0; k < 256; k++) {
			for (v = k, j = 0; j < 8; j++) v = v & 1 ? 0xEDB88320u ^ (v >> 1) : v >> 1;
			crc_table[k] = v;
		}
	}
	c ^= 0xFFFFFFFFu;
	for (i = 0; i < n; i++) c = crc_table[(c ^ p[i]) & 0xFF] ^ (c >> 8);
	return c ^ 0xFFFFFFFFu;
}

static void put32(unsigned char *p, uint32_t v) { p[0] = v >> 24; p[1] = v >> 16; p[2] = v >> 8; p[3] = v; }

static void wr(int fd, const void *p, size_t n)
{
	const char *c = p;
	while (n) {
		ssize_t k = write(fd, c, n);
		if (k <= 0) return;
		c += k; n -= (size_t)k;
	}
}

static void chunk(int fd, const char *type, const unsigned char *data, uint32_t len)
{
	unsigned char h[8];
	uint32_t c;
	put32(h, len);
	memcpy(h + 4, type, 4);
	wr(fd, h, 8);
	if (len) wr(fd, data, len);
	c = crc(crc(0, h + 4, 4), data, len);
	put32(h, c);
	wr(fd, h, 4);
}

/* an RGB PNG with stored (uncompressed) deflate blocks; its buffers are mmap'd and the file is
   written with write(2), so that writing frames does not change the game's heap */
static void write_png(const char *path, const unsigned char *rgb, int w, int h)
{
	size_t raw_len = (size_t)h * (1 + 3 * w), nblocks = (raw_len + 65534) / 65535;
	size_t zlen = 2 + raw_len + 5 * nblocks + 4, i, o = 0, off = 0;
	unsigned char *raw = mmap(NULL, raw_len, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
	unsigned char *z = mmap(NULL, zlen, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
	unsigned char ihdr[13];
	uint32_t a = 1, b = 0;
	int f, y;
	for (y = 0; y < h; y++) {
		raw[(size_t)y * (1 + 3 * w)] = 0;
		memcpy(raw + (size_t)y * (1 + 3 * w) + 1, rgb + (size_t)y * 3 * w, 3 * w);
	}
	z[o++] = 0x78; z[o++] = 0x01;
	while (off < raw_len) {
		size_t n = raw_len - off > 65535 ? 65535 : raw_len - off;
		z[o++] = off + n == raw_len;
		z[o++] = n & 0xFF; z[o++] = n >> 8; z[o++] = ~n & 0xFF; z[o++] = (~n >> 8) & 0xFF;
		memcpy(z + o, raw + off, n);
		o += n; off += n;
	}
	for (i = 0; i < raw_len; i++) { a = (a + raw[i]) % 65521; b = (b + a) % 65521; }
	put32(z + o, (b << 16) | a); o += 4;
	f = open(path, O_WRONLY | O_CREAT | O_TRUNC, 0644);
	if (f >= 0) {
		wr(f, "\x89PNG\r\n\x1a\n", 8);
		put32(ihdr, w); put32(ihdr + 4, h);
		ihdr[8] = 8; ihdr[9] = 2; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
		chunk(f, "IHDR", ihdr, 13);
		chunk(f, "IDAT", z, (uint32_t)o);
		chunk(f, "IEND", NULL, 0);
		close(f);
	}
	munmap(raw, raw_len); munmap(z, zlen);
}

/* called by our SDL's DUMMY_UpdateRects for every screen update */
void fbshim_update(SDL_Surface *s, int numrects, SDL_Rect *rects)
{
	static unsigned char *rgb;
	static size_t rgb_size;
	SDL_PixelFormat *fmt;
	uint32_t h = 0x811C9DC5u;
	int x, y, bpp;
	(void)numrects; (void)rects;
	if (!s || !s->pixels) return;
	fmt = s->format;
	bpp = fmt->BytesPerPixel;
	if ((size_t)s->w * s->h * 3 > rgb_size) {
		rgb_size = (size_t)s->w * s->h * 3;
		rgb = realloc(rgb, rgb_size);
	}
	for (y = 0; y < s->h; y++) {
		const unsigned char *row = (const unsigned char *)s->pixels + (size_t)y * s->pitch;
		for (x = 0; x < s->w; x++) {
			Uint32 p = 0;
			unsigned char c[3];
			int k;
			memcpy(&p, row + (size_t)x * bpp, bpp);
			c[0] = (unsigned char)(((p & fmt->Rmask) >> fmt->Rshift) << fmt->Rloss);
			c[1] = (unsigned char)(((p & fmt->Gmask) >> fmt->Gshift) << fmt->Gloss);
			c[2] = (unsigned char)(((p & fmt->Bmask) >> fmt->Bshift) << fmt->Bloss);
			for (k = 0; k < 3; k++) { h ^= c[k]; h *= 16777619u; }
			memcpy(rgb + ((size_t)y * s->w + x) * 3, c, 3);
		}
	}
	tr("F %llu %08x\n", (unsigned long long)vt, h);
	if (frames_dir[0]) {
		char path[1100];
		snprintf(path, sizeof path, "%s/%06lu.png", frames_dir, frame_index);
		write_png(path, rgb, s->w, s->h);
	}
	frame_index++;
}

