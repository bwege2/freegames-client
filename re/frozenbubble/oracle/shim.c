/*
 * The Frozen Bubble 2.2.0 oracle's shim (work/libfbshim.so, loaded with LD_PRELOAD by run.sh).
 * It makes a run of the original game deterministic and writes its trace.
 *
 *   clock   virtual milliseconds, 0 at start. Our SDL 1.2.15 (patches/sdl-oracle-hooks.patch) asks
 *           fbshim_get_ticks() for SDL_GetTicks and fbshim_delay() for SDL_Delay, so SDL's own uses
 *           (key repeat, SDL_WaitEvent) run on it too. SDL_Delay on the main thread advances the
 *           clock and returns at once; on other threads (SDL's timer thread) it really sleeps and
 *           does not touch the clock. libc sleep(n) advances by n*1000; time(), gettimeofday() and
 *           clock_gettime(CLOCK_REALTIME) return the session's epoch plus the virtual time.
 *   input   the session's events go into SDL's own queue from the dummy video driver's PumpEvents
 *           (fbshim_next_event hands over every event due at the current virtual time); SDL's
 *           queue, key state, mod state, key repeat, unicode and SDL_WaitEvent are SDL's.
 *   video   the dummy driver's screen is 640x480 XRGB8888; each UpdateRects (SDL_Flip,
 *           SDL_UpdateRect(s), also with 0 rects) calls fbshim_update: one F line.
 *   mixer   every Mix_* call of SDL_perl and c_stuff lands here: no audio, a model in virtual time.
 *   threads pango 1.57 matches fonts in a "[pango] fontconfig" thread per font map; its timing
 *           changed the main thread's heap (frees from the other thread), so the addresses Perl
 *           puts into hash keys (HASH(0x...)) and with them hash order varied from run to run.
 *           The shim creates no such thread: the queued work runs on the main thread when pango
 *           waits for it (g_cond_wait), in queue order. ASLR is off (run.sh: setarch -R).
 *   text    SDLPango_CreateSurfaceDraw is wrapped: SDL_Pango renders (real size), then the pixels
 *           become a placeholder (see pango_placeholder).
 *
 * Environment: ORACLE_SESSION (session file), ORACLE_TRACE (trace output), ORACLE_FRAMES (optional
 * directory: every frame as NNNNNN.png).
 *
 * Trace lines (ticks = virtual ms):
 *   F <ticks> <fnv1a32 of R,G,B bytes of the 640x480 screen, row-major, 8 hex digits>
 *   P <ticks> <text utf8 hex> <surface w>x<h> <x>,<y>,<w>,<h> [<x>,<y>,<w>,<h>...]   (one per
 *     painted run rectangle, clipped to the surface; none for empty text)
 *   PW <ticks> <text utf8 hex> <w> <h>       SDLPango_GetLayoutWidth/Height
 *   S <ticks> <chunk> <channel asked> <loops>      Mix_PlayChannel(Timed)
 *   S <ticks> halt <channel>                       Mix_HaltChannel
 *   M <ticks> play <music> <loops> | fadein <music> <loops> <ms> <pos> | fadeout <ms> | halt |
 *     pause | resume | rewind | position <pos> | volume <v> | stopped (end of a fade-out)
 *   V <ticks> chunk <name> <v> | channel <ch> <v>
 *   A <ticks> open <freq> <format> <channels> <chunksize> | close | allocate <n>
 *   W <ticks> cursor <toggle> | fullscreen | warp <x> <y>
 *   X <ticks> end | exit <status> | stall
 */
