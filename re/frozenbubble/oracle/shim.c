{
	fmusic *m;
	if (!file || access(file, R_OK) != 0) { SDL_SetError("Couldn't open '%s'", file ? file : "(null)"); return NULL; }
	m = calloc(1, sizeof *m);
	snprintf(m->name, sizeof m->name, "%s", base(file));
	return (Mix_Music *)m;
}

void Mix_FreeMusic(Mix_Music *mm)
{
	fmusic *m = (fmusic *)mm;
	if (!m) return;
	music_update();
	if (m == music_cur) {
		/* SDL_mixer 1.2.12: wait (SDL_Delay(100) steps) for a fade-out to end, then halt */
		while (music_cur == m && music_fading == MIX_FADING_OUT) { SDL_Delay(100); music_update(); }
		if (music_cur == m) { music_cur = NULL; music_fading = MIX_NO_FADING; }
	}
	free(m);
}

int Mix_VolumeChunk(Mix_Chunk *c, int v)
{
	int prev;
	if (!c) return -1;
	prev = c->volume;
	if (v >= 0) {
		if (v > MIX_MAX_VOLUME) v = MIX_MAX_VOLUME;
		c->volume = (Uint8)v;
		tr("V %llu chunk %s %d\n", (unsigned long long)vt, ((fchunk *)c)->name, v);
	}
	return prev;
}

int Mix_Volume(int ch, int v)
{
	int prev = 0, i;
	init_channels();
	if (ch == -1) {
		for (i = 0; i < nchannels; i++) prev += Mix_Volume(i, v);
		return nchannels ? prev / nchannels : 0;
	}
	if (ch < 0 || ch >= nchannels) return 0;
	prev = chan_volume[ch];
	if (v >= 0) {
		if (v > MIX_MAX_VOLUME) v = MIX_MAX_VOLUME;
		chan_volume[ch] = v;
		tr("V %llu channel %d %d\n", (unsigned long long)vt, ch, v);
	}
	return prev;
}

int Mix_VolumeMusic(int v)
{
	int prev = music_volume;
	if (v >= 0) {
		if (v > MIX_MAX_VOLUME) v = MIX_MAX_VOLUME;
		music_volume = v;
		tr("M %llu volume %d\n", (unsigned long long)vt, v);
	}
	return prev;
}

/* chunk lengths are not modelled: a played chunk does not occupy its channel */
static int next_channel;
int Mix_PlayChannelTimed(int ch, Mix_Chunk *c, int loops, int ticks)
{
	(void)ticks;
	if (!c) return -1;
	tr("S %llu %s %d %d\n", (unsigned long long)vt, ((fchunk *)c)->name, ch, loops);
	if (ch >= 0) return ch;
	ch = nchannels ? next_channel % nchannels : 0;
	next_channel++;
	return ch;
}

int Mix_FadeInChannelTimed(int ch, Mix_Chunk *c, int loops, int ms, int ticks)
{
	(void)ms;
	return Mix_PlayChannelTimed(ch, c, loops, ticks);
}

