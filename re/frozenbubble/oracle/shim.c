/* ------------------------------------------------------------------ state */

static FILE *trace;
static char frames_dir[1024];
static unsigned long frame_index;
static uint64_t vt;               /* virtual ms */
static uint64_t end_time = UINT64_MAX;
static time_t epoch = 1278000000;
static pthread_t main_thread;
static unsigned long idle_pumps;   /* pumps since the clock last advanced */

typedef struct { int type, sym, unicode, x, y, button; } fbshim_event; /* as in the SDL patch */
typedef struct { uint64_t t; long seq; fbshim_event e; } sev;
static sev *events;
static size_t nevents, next_event;

static void tr(const char *fmt, ...)
{
	va_list ap;
	if (!trace) return;
	va_start(ap, fmt);
	vfprintf(trace, fmt, ap);
	va_end(ap);
}

static void die_exit(int status)
{
	if (trace) fflush(trace);
	syscall(SYS_exit_group, status);
	for (;;) ;
}

static void check_end(void)
{
	if (vt >= end_time) {
		tr("X %llu end\n", (unsigned long long)vt);
		die_exit(0);
	}
}

static void advance(uint64_t ms)
{
	if (!ms) return;
	vt += ms;
	idle_pumps = 0;
	check_end();
}

/* ------------------------------------------------------------------ session */

#include "keynames.h"   /* generated by build.sh from SDL_keysym.h: { "left", SDLK_LEFT }, ... */

static int keysym_of(const char *name)
{
	size_t i;
	for (i = 0; i < sizeof(keynames) / sizeof(keynames[0]); i++)
		if (!strcmp(keynames[i].name, name)) return keynames[i].sym;
	fprintf(stderr, "fbshim: unknown key name '%s'\n", name);
	die_exit(3);
	return 0;
}

static int shift_down;
/* the character X11 (XLookupString, US layout) gives for a key press */
static int default_unicode(int sym)
{
	static const char *plain = "`1234567890-=[]\\;',./", *shifted = "~!@#$%^&*()_+{}|:\"<>?";
	if (sym >= 'a' && sym <= 'z') return shift_down ? sym - 32 : sym;
	if (sym >= 32 && sym <= 126) {
		const char *p = strchr(plain, sym);
		if (shift_down && p) return shifted[p - plain];
		return sym;
	}
	if (sym == SDLK_BACKSPACE || sym == SDLK_TAB || sym == SDLK_RETURN || sym == SDLK_ESCAPE ||
	    sym == SDLK_DELETE) return sym;
	if (sym == SDLK_KP_ENTER) return 13;
	return 0;
}

static void add_event(uint64_t t, long seq, int type, int sym, int unicode, int x, int y, int button)
{
	static size_t cap;
	if (nevents == cap) {
		cap = cap ? cap * 2 : 256;
		events = realloc(events, cap * sizeof(*events));
	}
	events[nevents].t = t;
	events[nevents].seq = seq;
	events[nevents].e.type = type;
	events[nevents].e.sym = sym;
	events[nevents].e.unicode = unicode;
	events[nevents].e.x = x;
	events[nevents].e.y = y;
	events[nevents].e.button = button;
	nevents++;
}

static int cmp_sev(const void *a, const void *b)
{
	const sev *x = a, *y = b;
	if (x->t != y->t) return x->t < y->t ? -1 : 1;
	return x->seq < y->seq ? -1 : x->seq > y->seq;
}

static void load_session(const char *path)
{
	FILE *f = fopen(path, "r");
	char line[4096];
	long lineno = 0;
	if (!f) { fprintf(stderr, "fbshim: cannot open session %s\n", path); die_exit(3); }
	while (fgets(line, sizeof line, f)) {
		char w[6][256];
		unsigned long long t;
		int n;
		lineno++;
		line[strcspn(line, "\r\n")] = 0;
		if (line[0] == '#') {
			long long e;
			if (sscanf(line, "# time %lld", &e) == 1) epoch = (time_t)e;
			continue;
		}
		n = sscanf(line, "%llu %255s %255s %255s %255s %255s %255s", &t, w[0], w[1], w[2], w[3], w[4], w[5]);
		if (n <= 0) continue;
		n--;
		/* events of a line keep the line's order: seq = 4*line (+1, +2 for generated ones) */
		if (n >= 1 && !strcmp(w[0], "end")) {
			if (t < end_time) end_time = t;
		} else if (n >= 3 && !strcmp(w[0], "key")) {
			int sym = keysym_of(w[2]);
			if (!strcmp(w[1], "down")) {
				int u = n >= 4 ? (int)strtol(w[3], NULL, 0) : -1;
				add_event(t, lineno * 4, 1, sym, u, 0, 0, 0);
			} else if (!strcmp(w[1], "up")) {
				add_event(t, lineno * 4, 2, sym, 0, 0, 0, 0);
			} else goto bad;
		} else if (n >= 2 && !strcmp(w[0], "tap")) {
			int sym = keysym_of(w[1]);
			unsigned long hold = n >= 3 ? strtoul(w[2], NULL, 10) : 40;
			int u = n >= 4 ? (int)strtol(w[3], NULL, 0) : -1;
			add_event(t, lineno * 4, 1, sym, u, 0, 0, 0);
			add_event(t + hold, lineno * 4 + 1, 2, sym, 0, 0, 0, 0);
		} else if (n >= 4 && !strcmp(w[0], "mouse")) {
			int x = atoi(w[2]), y = atoi(w[3]);
			if (!strcmp(w[1], "move")) add_event(t, lineno * 4, 3, 0, 0, x, y, 0);
			else if (n >= 5 && !strcmp(w[1], "down")) add_event(t, lineno * 4, 4, 0, 0, x, y, atoi(w[4]));
			else if (n >= 5 && !strcmp(w[1], "up")) add_event(t, lineno * 4, 5, 0, 0, x, y, atoi(w[4]));
			else goto bad;
		} else {
		bad:
			fprintf(stderr, "fbshim: %s:%ld: cannot parse '%s'\n", path, lineno, line);
			die_exit(3);
		}
	}
	fclose(f);
	qsort(events, nevents, sizeof(*events), cmp_sev);
}

/* called by our SDL's DUMMY_PumpEvents until it returns 0 */
int fbshim_next_event(fbshim_event *e)
{
	if (next_event < nevents && events[next_event].t <= vt) {
		*e = events[next_event++].e;
		if (e->type == 1 || e->type == 2) {
			if (e->sym == SDLK_LSHIFT || e->sym == SDLK_RSHIFT) {
				static int l, r;
				if (e->sym == SDLK_LSHIFT) l = e->type == 1; else r = e->type == 1;
				shift_down = l || r;
			}
			if (e->type == 1 && e->unicode < 0) e->unicode = default_unicode(e->sym);
		}
		return 1;
	}
	if (++idle_pumps > 100000) {
		tr("X %llu stall\n", (unsigned long long)vt);
		die_exit(2);
	}
	return 0;
}

/* ------------------------------------------------------------------ clock */

Uint32 fbshim_get_ticks(void) { return (Uint32)vt; }

int fbshim_delay(Uint32 ms)
{
	if (!pthread_equal(pthread_self(), main_thread)) return 0;
	advance(ms);
	return 1;
}

unsigned int sleep(unsigned int s)
{
	advance((uint64_t)s * 1000);
	return 0;
}

time_t time(time_t *t)
{
	time_t r = epoch + (time_t)(vt / 1000);
	if (t) *t = r;
	return r;
}

int gettimeofday(struct timeval *restrict tv, void *restrict tz)
{
	struct timeval *volatile v = tv;
	(void)tz;
	if (v) {
		tv->tv_sec = epoch + (time_t)(vt / 1000);
		tv->tv_usec = (suseconds_t)(vt % 1000) * 1000;
	}
	return 0;
}

int clock_gettime(clockid_t clk, struct timespec *ts)
{
	static int (*real)(clockid_t, struct timespec *);
	if (clk == CLOCK_REALTIME || clk == CLOCK_REALTIME_COARSE) {
		ts->tv_sec = epoch + (time_t)(vt / 1000);
		ts->tv_nsec = (long)(vt % 1000) * 1000000L;
		return 0;
	}
	if (!real) real = (int (*)(clockid_t, struct timespec *))dlsym(RTLD_NEXT, "clock_gettime");
	return real(clk, ts);
}

/* ------------------------------------------------------------------ randomness */
/* fontconfig (FcRandom = arc4random when libc has it) draws the levels of its cache skip list
   from it, so the sizes of its allocations, and with them every later heap address, varied from
   run to run. Here they come from a fixed xorshift sequence. getrandom() likewise. */
static uint64_t rnd_state = 0x9E3779B97F4A7C15ull;
static uint32_t rnd32(void)
{
	rnd_state ^= rnd_state << 13;
	rnd_state ^= rnd_state >> 7;
	rnd_state ^= rnd_state << 17;
	return (uint32_t)(rnd_state >> 16);
}
uint32_t arc4random(void) { return rnd32(); }
uint32_t arc4random_uniform(uint32_t n) { return n ? rnd32() % n : 0; }
void arc4random_buf(void *buf, size_t n)
{
	unsigned char *p = buf;
	while (n--) *p++ = (unsigned char)rnd32();
}
ssize_t getrandom(void *buf, size_t n, unsigned int flags)
{
	(void)flags;
	arc4random_buf(buf, n);
	return (ssize_t)n;
}
int getentropy(void *buf, size_t n) { arc4random_buf(buf, n); return 0; }

