/** rules for the zebravalues of heptagons. */
export function zebra_heptagon(parent: number, dir: number): number {
  if (S3() === 4) {
    const mm = (parent % 10 + S7() - dir) % S7();
    const mv = Math.trunc(parent / 10);
    // whichbright: d&1
    if (S7() === 5) switch (mm) {
      case 0:
        return 10 * (mv ^ 1);
      case 1:
        return 10 * (mv ^ 2) + 4;
      case 2:
        return 10 * (mv ^ 4) + 3;
      case 3:
        return 10 * (mv ^ 4) + 2;
      case 4:
        return 10 * (mv ^ 2) + 1;
    }
    if (S7() === 7) switch (mm) {
      case 0:
        return 10 * (mv ^ 2);
      case 1:
        return 10 * (mv ^ 1) + 6;
      case 2:
        return 10 * (mv ^ 2) + 5;
      case 3:
        return 10 * (mv ^ 4) + 4;
      case 4:
        return 10 * (mv ^ 4) + 3;
      case 5:
        return 10 * (mv ^ 2) + 2;
      case 6:
        return 10 * (mv ^ 1) + 1;
    }
    if (S7() === 6) switch (mm) {
      case 0:
        return 10 * (mv ^ 2);
      case 1:
        return 10 * (mv ^ 1) + 5;
      case 2:
        return 10 * (mv ^ 2) + 4;
      case 3:
        return 10 * (mv ^ 1) + 3;
      case 4:
        return 10 * (mv ^ 2) + 2;
      case 5:
        return 10 * (mv ^ 1) + 1;
    }
  }
  if (S7() === 8 && dir > 3) dir--;
  return zebratable[Math.trunc(parent / 10) - 4][(70 + dir - (parent % 10)) % 7];
}

export function fifty_38(f: number, d: number): number {
  // This creates the 'p' pattern for the a38 geometry.
  // Hexagons have codes 4 and 8, while octagons have 0, 1, 2.
  // Heptagons also have a 'dock flag' which is flipped
  // for almost-adjacent octagons of the same code

  // f&1 is which direction is the hexagon with code '4'

  // c=((f>>1)&3) is 0, 1, or 2
  const c = ((f >> 1) & 3);

  // (f>>3)&3: in which direction is c increasing by one (keeping the dock flag)
  const ssub = (f >> 3) & 3;

  // f&32: dock flags
  const dockflip = [[1 + 24, 2 + 0, 1 + 32 + 8, 2 + 32 + 0], [1 + 8, 2 + 32 + 16, 1 + 32 + 24, 2 + 16]];

  const d2 = (d - ssub) & 3;
  const dock = (f >> 5) & 1;

  return ((f ^ d ^ 1) & 1)
    + (((c + (dockflip[dock][d2] & 3)) % 3) << 1)
    + (dockflip[dock][d2] & ~3);
}

