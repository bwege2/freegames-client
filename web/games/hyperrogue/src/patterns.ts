export function firstfiftyval(d: number): number {
  if (S7() === 8 && d > 3) d--;
  return fiftytable[0][d];
}

export function nextfiftyval(par: number, gpar: number, d: number): number {
  if (S7() === 8 && d > 3) d--;
  for (let i = 0; i < 7; i++) if (fiftytable[par][i] === gpar)
    return fiftytable[par][(i + d) % 7];
  if (weirdhyperbolic()) return 0;
  // printf("fifty pattern error!\n"); exit(1);
  throw new hr_exception('fifty pattern error!');
}

