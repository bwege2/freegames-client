test('s2 svg: printf %f (fmtF) as glibc', () => {
  for (const [x, p, s] of F) assert.equal(fmtF(x, p), s, `%.${p}f of ${x}`);
});

test('s2 svg: cta and fixgamma', () => {
  const cta: string[] = [];
  for (let c = 0; c < 256; c++) cta.push(fmtF(svg_cta(c), 3));
  assert.equal(cta.join(' '), CTA);
  const g = G.shot_gamma;
  try {
    for (let c = 0; c < 256; c++) {
      const col = ((c << 24) | (c << 16) | (c << 8) | 0x7F) >>> 0;
      assert.equal(svg_fixgamma(col), col, 'gamma 1 changes nothing');
    }
    G.shot_gamma = 2.2;
    const out: number[] = [];
    for (let c = 0; c < 256; c++) out.push(svg_fixgamma(c << 8) >>> 8);
    assert.equal(out.join(' '), GAMMA22);
  } finally { G.shot_gamma = g; }
});

test('s2 svg: coord and stylestr as in the oracle goldens', () => {
  // golden/draw-bare.txt.gz (640x480, divby 10): the disk's boundary circle and the first floor; the floor's
  // outline width is radius * linewidth / 256 = 2400 * 1 / 256 (svg::polygon)
  assert.equal(svg_coord(3200), '320.0');
  assert.equal(svg_coord(2399), '239.9');
  assert.equal(svg_stylestr(0, 0x0000FFFF, 10),
    'style="stroke:#0000ff;stroke-opacity:1.000;stroke-width:1.000000px;fill:#000000;fill-opacity:0.000"');
  assert.equal(svg_stylestr(0x20203FFF, 0x000000FF, 2400 * 1 / 256),
    'style="stroke:#000000;stroke-opacity:1.000;stroke-width:0.937500px;fill:#20203f;fill-opacity:1.000"');
  const d = G.svg_divby;
  try {
    G.svg_divby = 1; // `svg ... screen`: whole pixels
    assert.equal(svg_coord(391), '391');
    G.svg_divby = 100;
    assert.equal(svg_coord(12345), '123.45');
  } finally { G.svg_divby = d; }
});
