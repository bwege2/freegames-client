"""The keysym names of <X11/keysymdef.h> (as the client oracle's xstub.c has them, in header order) for
Latin-1 (0x0000-0x00ff) and the function/keypad/modifier keys (0xfe00-0xffff), as a TS module."""
import re, sys
out = []
for line in open(sys.argv[1]):
    m = re.match(r'^#define XK_([A-Za-z0-9_]+)\s+0x([0-9a-fA-F]+)', line)
    if not m:
        continue
    name, val = m.group(1), int(m.group(2), 16)
    if val <= 0xff or 0xfe00 <= val <= 0xffff:
        out.append((name, val))
print('// X11 keysym names and values (<X11/keysymdef.h>, the X Window System protocol\'s keysym encoding), in')
print('// header order: Latin-1 and the TTY, function, cursor, keypad and modifier keys. Generated by')
print('// web/games/xpilot/assets/keysyms.py; the client oracle\'s recording Xlib (re/xpilot/oracle/client/xstub.c)')
print('// has the same table, so XStringToKeysym and XKeysymToString answer as there.')
print('export const KEYSYMS: [string, number][] = [')
line = '  '
for name, val in out:
    item = "['%s', 0x%x], " % (name, val)
    if len(line) + len(item) > 118:
        print(line.rstrip())
        line = '  '
    line += item
print(line.rstrip())
print('];')
