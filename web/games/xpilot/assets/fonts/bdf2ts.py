"""Converts the misc-fixed bold BDFs (public domain, X.org font-misc-misc 1.1.3) into a TS module:
for codes 0..255 (ISO 8859-1 = Unicode 0..255) the glyph rows as hex, cell-sized (width x height),
top row first, bit 7 of the first byte = leftmost pixel."""
import sys

def read(path):
    glyphs = {}
    ascent = descent = None
    with open(path) as f:
        lines = f.read().split('\n')
    i = 0
    while i < len(lines):
        l = lines[i]
        if l.startswith('FONT_ASCENT'): ascent = int(l.split()[1])
        if l.startswith('FONT_DESCENT'): descent = int(l.split()[1])
        if l.startswith('FONTBOUNDINGBOX'):
            fbw, fbh, fbx, fby = map(int, l.split()[1:])
        if l.startswith('STARTCHAR'):
            enc = None; bbx = None; rows = []
            i += 1
            while not lines[i].startswith('ENDCHAR'):
                t = lines[i]
                if t.startswith('ENCODING'): enc = int(t.split()[1])
                elif t.startswith('BBX'): bbx = list(map(int, t.split()[1:]))
                elif t.startswith('BITMAP'):
                    i += 1
                    while not lines[i].startswith('ENDCHAR'):
                        rows.append(lines[i].strip()); i += 1
                    break
                i += 1
            if enc is not None and 0 <= enc < 256:
                glyphs[enc] = (bbx, rows)
        i += 1
    return fbw, fbh, ascent, descent, glyphs

def cell(fbw, fbh, ascent, descent, bbx, rows):
    # cell rows: y from top (ascent-1) down to -descent
    w, h, xo, yo = bbx
    out = [0] * (ascent + descent)
    for r, hexrow in enumerate(rows):
        v = int(hexrow, 16)
        nbits = len(hexrow) * 4
        # row r is at baseline offset yo + h - 1 - r
        by = yo + h - 1 - r
        cy = ascent - 1 - by
        if not (0 <= cy < ascent + descent): continue
        for b in range(w):
            if v & (1 << (nbits - 1 - b)):
                x = xo + b
                if 0 <= x < fbw:
                    out[cy] |= 1 << x
    return out

def main():
    out = ['// misc-fixed bold glyphs for ISO 8859-1 (X.org font-misc-misc 1.1.3, 7x13B.bdf and 9x15B.bdf: public',
           '// domain), generated by web/games/xpilot/assets/fonts/bdf2ts.py. One string per font: 256 glyphs, each `height`',
           '// rows of `width` bits (bit x = column x), as hex, `bytesPerRow` bytes per row, little-endian.',
           '']
    for name, path in [('FIXED_BOLD_13', sys.argv[1]), ('FIXED_BOLD_15', sys.argv[2])]:
        fbw, fbh, asc, dsc, glyphs = read(path)
        bpr = (fbw + 7) // 8
        hexs = []
        missing = []
        for c in range(256):
            g = glyphs.get(c) or glyphs.get(0)
            if c not in glyphs: missing.append(c)
            rows = cell(fbw, fbh, asc, dsc, *g)
            for r in rows:
                for k in range(bpr):
                    hexs.append('%02x' % ((r >> (8 * k)) & 0xff))
        out.append('/** %s: %dx%d, ascent %d, descent %d; codes without a glyph use glyph 0: %s */' % (path.split('/')[-1], fbw, asc + dsc, asc, dsc, missing))
        out.append('export const %s = { width: %d, ascent: %d, descent: %d, bytesPerRow: %d, glyphs:' % (name, fbw, asc, dsc, bpr))
        s = ''.join(hexs)
        chunks = [s[i:i + 120] for i in range(0, len(s), 120)]
        out.append('  ' + ' +\n  '.join("'%s'" % c for c in chunks) + ' };')
        out.append('')
    sys.stdout.write('\n'.join(out))

main()
