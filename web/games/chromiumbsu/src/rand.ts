/** Global::randI/randF/randS/randIndex and the FRAND, SRAND, IRAND macros (src/define.h) */
export class RandTables {
  randI = new Int32Array(256);
  randF = new Float32Array(256);
  randS = new Float32Array(256);
  randIndex = 0;

  /** Global::generateRandom(r) */
  generate(rand: GlibcRand | null): void {
    this.randIndex = 0;
    for (let i = 0; i < 256; i++) {
      if (rand) {
        this.randI[i] = rand.next();
        this.randS[i] = 2.0 * (0.5 - rand.next() / RAND_MAX);
        this.randF[i] = rand.next() / RAND_MAX;
      } else {
        this.randI[i] = RAND_DATA[i];
        this.randS[i] = 2.0 * (0.5 - RAND_DATA[i] / RAND_MAX);
        this.randF[i] = RAND_DATA[i] / RAND_MAX;
      }
    }
  }
  /** FRAND: 0..1 (float) */
  get F(): number { return this.randF[(++this.randIndex) % 256]; }
  /** SRAND: -1..1 (float) */
  get S(): number { return this.randS[(++this.randIndex) % 256]; }
  /** IRAND: 0..RAND_MAX (int) */
  get I(): number { return this.randI[(++this.randIndex) % 256]; }
}
