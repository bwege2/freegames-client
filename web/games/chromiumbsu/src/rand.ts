// The game draws from three tables of 256 numbers made once at start (Global::generateRandom,
// src/Global.cpp) with the C library's rand() after srand(time(NULL)) (src/main.cpp). rand() is
// glibc's (the Linux build): random_r TYPE_3, an additive feedback generator, reproduced here.

export const RAND_MAX = 2147483647;

/** glibc srand()/rand() */
export class GlibcRand {
  private readonly state = new Int32Array(31);
  private front = 3;
  private rear = 0;
  constructor(seed: number) {
    // __srandom_r: state[0] = seed (0 counts as 1), state[i] = 16807 * state[i-1] % 2147483647
    // (Schrage's method on a signed 32-bit int), then 310 numbers are thrown away
    let word = (seed >>> 0 === 0 ? 1 : seed) | 0;
    this.state[0] = word;
    for (let k = 1; k < 31; k++) {
      const hi = Math.trunc(word / 127773);
      const lo = word % 127773;
      word = 16807 * lo - 2836 * hi;
      if (word < 0) word += 2147483647;
      this.state[k] = word;
    }
    for (let k = 0; k < 310; k++) this.next();
  }
  /** rand(): 0 .. RAND_MAX */
  next(): number {
    const s = this.state;
    s[this.front] = s[this.front] + s[this.rear];
    const result = s[this.front] >>> 1;
    if (++this.front >= 31) { this.front = 0; ++this.rear; } else if (++this.rear >= 31) this.rear = 0;
    return result;
  }
}

