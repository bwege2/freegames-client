/** OptionAgent: string parameters; persistent ones go to the user's options file */
export class Options {
  params = new Map<string, string>();
  persistent = new Set<string>();
  watchers: ((name: string) => void)[] = [];
  onPersist: () => void = () => {};

  getParam(name: string, def = ''): string {
    const v = this.params.get(name);
    return v === undefined || v === '' ? def : v;
  }
  setParam(name: string, value: string | number | boolean): void {
    this.params.set(name, String(typeof value === 'boolean' ? (value ? 1 : 0) : value));
    for (const w of this.watchers) w(name);
  }
  setDefault(name: string, value: string | number): void {
    if (!this.params.has(name)) this.setParam(name, value);
  }
  setPersistent(name: string, value: string | number | boolean): void {
    this.persistent.add(name);
    this.setParam(name, value);
    this.onPersist();
  }
  getAsInt(name: string, def = 0): number {
    const v = this.params.get(name);
    if (v === undefined) return def;
    const n = parseInt(v, 10);
    return Number.isNaN(n) ? def : n;
  }
  getAsBool(name: string, def = false): boolean {
    const v = this.params.get(name);
    if (v === undefined || v === '') return def;
    return this.getAsInt(name, def ? 1 : 0) !== 0;
  }
  /** script/options.lua, as OptionAgent::savePersistent writes it */
  serialize(): string {
    let out = '-- this file is generated by game\n';
    for (const k of [...this.persistent].sort()) out += `setParam("${k}", "${this.params.get(k) ?? ''}")\n`;
    return out;
  }
}

/** the data files of the game (read only) and the user's own files (saves, solved, options) */
export interface DataFiles {
  /** a data file exists (images, sounds, scripts) */
  has(path: string): boolean;
  /** the text of a script, as bytes in a string */
  text(path: string): string | null;
}

export class Vfs {
  data: DataFiles;
  options: Options;
  /** the user dir: files the game wrote */
  user = new Map<string, string>();
  onUserWrite: (path: string) => void = () => {};
  constructor(data: DataFiles, options: Options) {
    this.data = data;
    this.options = options;
  }

  private localize(file: string): string {
    const dot = file.lastIndexOf('.');
    if (dot < 0) return file;
    const lang = this.options.getParam('lang');
    if (lang === 'en' || lang === '') return file;
    const slash = file.lastIndexOf('/');
    if (slash >= 0 && dot < slash) return file;
    return file.slice(0, dot) + '__' + lang + file.slice(dot);
  }

  /** Path::dataReadPath: the user's file, else the system file; a localized name__lang.ext first */
  resolve(file: string): { user: boolean; path: string } {
    const loc = this.localize(file);
    if (this.user.has(loc)) return { user: true, path: loc };
    if (loc !== file && this.user.has(file)) return { user: true, path: file };
    if (loc !== file && this.data.has(loc)) return { user: false, path: loc };
    return { user: false, path: file };
  }

  exists(file: string): boolean {
    const r = this.resolve(file);
    return r.user ? true : this.data.has(r.path);
  }

  /** the system path of a data file (images, sounds), localized */
  dataPath(file: string): string { return this.resolve(file).path; }

  readText(file: string): string | null {
    const r = this.resolve(file);
    if (r.user) return this.user.get(r.path) ?? null;
    return this.data.text(r.path);
  }

  write(file: string, content: string): void {
    this.user.set(file, content);
    this.onUserWrite(file);
  }
}

/** SubTitleAgent and Title: subtitles rise from the bottom of the screen */
export interface TextMeasure {
  width(text: string): number;
}

const TITLE_ROW = 26, TITLE_BASE = 20, TITLE_SPEED = 2, TITLE_BORDER = 20;
export const TITLE_LIMIT_Y = TITLE_BASE + 5 * TITLE_ROW;
const TIME_PER_CHAR = 2, TIME_MIN = 40;

export function utf8Length(s: string): number {
  let n = 0;
  for (let i = 0; i < s.length; i++) if ((s.charCodeAt(i) & 0xc0) !== 0x80) n++;
  return n;
}

export class Title {
  content: string;
  color: [number, number, number];
  x: number;
  y: number;
  finalY: number;
  limitY: number;
  mintime: number;
  screenH: number;
  constructor(baseY: number, finalY: number, bonusTime: number, limitY: number, content: string, color: [number, number, number], width: number, screenW: number, screenH: number) {
    this.content = content;
    this.color = color;
    this.screenH = screenH;
    this.x = Math.trunc((screenW - width) / 2);
    this.y = screenH - baseY;
    this.finalY = screenH - finalY;
    this.limitY = screenH - limitY;
    this.mintime = Math.max(TIME_MIN, utf8Length(content) * TIME_PER_CHAR) + bonusTime;
  }
  shiftUp(rate: number): void {
    this.mintime--;
    this.y -= rate;
    if (this.y < this.finalY) this.y = this.finalY;
  }
  shiftFinalUp(rate: number): void { this.finalY -= rate; }
  getY(): number { return this.screenH - this.y; }
  isGone(): boolean { return this.mintime < 0 || this.y < this.limitY; }
}

export class SubTitles {
  titles: Title[] = [];
  colors = new Map<string, [number, number, number]>();
  limitY = TITLE_LIMIT_Y;
  options: Options;
  measure: TextMeasure;
  constructor(options: Options, measure: TextMeasure) {
    this.options = options;
    this.measure = measure;
  }

  addFont(name: string, r: number, g: number, b: number): void {
    // ResColorPack is a multimap: getRes() returns the first one added
    if (!this.colors.has(name)) this.colors.set(name, [r, g, b]);
  }

  update(): void {
    if (this.titles.length > 0) {
      for (const t of this.titles) t.shiftUp(TITLE_SPEED);
      if (this.titles[0].isGone()) this.titles.shift();
    }
  }

  newSubtitle(original: string, fontname: string): void {
    const color = this.colors.get(fontname);
    if (!color) throw new Error(`no such resource: ${fontname}`);
    let subtitle = original;
    while (subtitle !== '') subtitle = this.splitAndCreate(subtitle, color);
  }

  private splitAndCreate(original: string, color: [number, number, number]): string {
    let subtitle = original;
    const screenW = this.options.getAsInt('screen_width');
    while (this.measure.width(subtitle) > screenW - 2 * TITLE_BORDER) subtitle = trimRest(subtitle);
    let rest = '';
    if (subtitle !== '') {
      this.newShortSubtitle(subtitle, color);
      if (original.length > subtitle.length) rest = original.slice(subtitle.length);
    }
    return rest;
  }

  private newShortSubtitle(subtitle: string, color: [number, number, number]): void {
    const startY = this.lowestY();
    const finalY = TITLE_BASE + TITLE_ROW;
    const bonusTime = Math.trunc((TITLE_BASE - startY + this.limitY - TITLE_LIMIT_Y) / TITLE_SPEED);
    // Title is rendered as " text " (renderTextOutlined adds spaces) but centred by the text's width
    const t = new Title(startY, finalY, bonusTime, this.limitY, subtitle, color, this.measure.width(subtitle),
      this.options.getAsInt('screen_width'), this.options.getAsInt('screen_height'));
    for (const o of this.titles) o.shiftFinalUp(TITLE_ROW);
    this.titles.push(t);
  }

  private lowestY(): number {
    let lowest = TITLE_BASE;
    if (this.titles.length > 0) lowest = Math.min(lowest, this.titles[this.titles.length - 1].getY() - TITLE_ROW);
    return lowest;
  }

  killTalks(): void { this.titles = []; }
  removeAll(): void { this.killTalks(); this.colors.clear(); }
}

/** SubTitleAgent::trimRest: cut at the last ' ' that is not in " x " */
function trimRest(buffer: string): string {
  let i;
  for (i = buffer.length - 1; i >= 0; --i) {
    if (buffer[i] === ' ' && !(i - 2 >= 0 && buffer[i - 2] === ' ')) break;
  }
  if (i <= 0) return buffer.length > 4 ? buffer.slice(0, buffer.length - 4) : '';
  return buffer.slice(0, i);
}

/** everything the game's states share */
export class Env {
  options: Options;
  vfs: Vfs;
  sound: SoundPlayer;
  subtitles: SubTitles;
  /** TimerAgent::getCycles() */
  cycles = 0;
  log: (msg: string) => void;
  constructor(data: DataFiles, sound: SoundPlayer, measure: TextMeasure, log: (msg: string) => void = () => {}) {
    this.options = new Options();
    this.vfs = new Vfs(data, this.options);
    this.sound = sound;
    this.subtitles = new SubTitles(this.options, measure);
    this.log = log;
  }

  split(s: string, sep: string): string[] { return cppSplit(s, sep); }
}
