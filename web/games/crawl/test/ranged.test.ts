// Ranged weapons and throwing: item-prop.cc launcher/missile data, attack.cc to-hit/damage,
// fight.cc throwing bonus, ammo destruction.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { Rng } from '../src/game/rng.ts';
import { createPlayer } from '../src/game/player.ts';
import { JOBS_BY_NAME, MISSILES, MISSILE_BY_ID, SPECIES_BY_NAME, WEAPON_BY_NAME } from '../src/game/data.ts';
import { isLauncher, makeMissile, makeWeapon, randomMissiles } from '../src/game/items.ts';
import { launchedProjectileName, playerRangedAttack } from '../src/game/combat.ts';
import { idx } from '../src/game/model.ts';
import type { Level, Monster } from '../src/game/model.ts';

function dummyLevel(): Level {
  return {
    key: 'D:1', branch: 'BRANCH_DUNGEON', depth: 1, absDepth: 1,
    cells: Array.from({ length: 80 * 70 }, () => ({ feat: 'DNGN_FLOOR', known: true, visible: true })),
    monsters: [], items: [], traps: [], shops: [], up: [], down: [], branches: [], visited: true, entry: idx(40, 35), layout: 'test',
  };
}

function dummyMonster(): Monster {
  return {
    uid: 1, def: 'MONS_RAT', name: 'rat', x: 41, y: 35, hp: 100, hpMax: 100, hd: 1, ac: 0, ev: 0,
    speed: 10, energy: 0, asleep: false, attitude: 'hostile', cooldown: 0, unique: false,
    confused: 0, slowed: 0, poisoned: 0, fleeing: 0, invisible: 0, known: true,
  };
}

test('launcher data is item-prop.cc', () => {
  const sling = WEAPON_BY_NAME.get('sling')!;
  assert.equal(sling.damage, 7);
  assert.equal(sling.skill, 'SK_RANGED_WEAPONS');
  const shortbow = WEAPON_BY_NAME.get('shortbow')!;
  assert.equal(shortbow.damage, 8);
  assert.equal(shortbow.hit, 2);
  const longbow = WEAPON_BY_NAME.get('longbow')!;
  assert.equal(longbow.damage, 14);
  const arbalest = WEAPON_BY_NAME.get('arbalest')!;
  assert.equal(arbalest.damage, 16);
  assert.equal(launchedProjectileName('WPN_SLING'), 'sling bullet');
  assert.equal(launchedProjectileName('WPN_SHORTBOW'), 'arrow');
  assert.equal(launchedProjectileName('WPN_ARBALEST'), 'bolt');
  assert.equal(launchedProjectileName('WPN_HAND_CANNON'), 'slug');
  assert.ok(isLauncher('WPN_LONGBOW'));
  assert.ok(!isLauncher('WPN_LONG_SWORD'));
});

test('missile data is item-prop.cc Missile_prop', () => {
  assert.equal(MISSILE_BY_ID.get('MI_DART')!.damage, 0);
  assert.equal(MISSILE_BY_ID.get('MI_DART')!.mulch, 12);
  assert.equal(MISSILE_BY_ID.get('MI_STONE')!.damage, 2);
  assert.equal(MISSILE_BY_ID.get('MI_STONE')!.mulch, 8);
  assert.equal(MISSILE_BY_ID.get('MI_JAVELIN')!.damage, 10);
  assert.equal(MISSILE_BY_ID.get('MI_JAVELIN')!.mulch, 20);
  assert.equal(MISSILE_BY_ID.get('MI_BOOMERANG')!.damage, 6);
  assert.ok(MISSILES.length >= 6);
});

test('thrown missiles stack and are generated by depth', () => {
  const r = new Rng(7n);
  for (let i = 0; i < 50; i++) {
    const m = randomMissiles(r, 5);
    assert.equal(m.cls, 'missile');
    assert.ok(MISSILE_BY_ID.has(m.id));
    assert.ok(m.qty >= 2);
  }
  const dart = makeMissile('MI_DART', 7);
  assert.equal(dart.qty, 7);
});

test('a ranged attack hits, damages and mulches a thrown stone', () => {
  const r = new Rng(7n);
  const p = createPlayer(SPECIES_BY_NAME.get('human')!, JOBS_BY_NAME.get('hunter')!, 'WPN_UNARMED', 'Test');
  p.gear.weapon = makeWeapon('WPN_SHORTBOW');
  p.skills.ranged_weapons.level = 10;
  p.skills.ranged_weapons.points = 1e6;
  const mon = dummyMonster();
  const level = dummyLevel();
  let killed = false;
  const ctx = {
    rng: r, player: p, level,
    msg: () => {}, onMonsterKilled: () => { killed = true; },
    onPlayerDamaged: () => {}, onPlayerKilled: () => {},
  };
  const out = playerRangedAttack(ctx, mon, p.gear.weapon, false);
  assert.equal(out.hit, true);
  assert.ok(mon.hp < 100, `hp ${mon.hp}`);
  assert.equal(out.destroyed, false, 'launchers have no ammo');
  void killed;
});

test('throwing a stone adds the fight.cc throwing damage bonus', () => {
  const r = new Rng(11n);
  const p = createPlayer(SPECIES_BY_NAME.get('human')!, JOBS_BY_NAME.get('hunter')!, 'WPN_UNARMED', 'Test');
  p.skills.throwing.level = 12;
  p.skills.throwing.points = 1e6;
  const stone = makeMissile('MI_STONE', 1);
  let damage = 0;
  for (let i = 0; i < 20; i++) {
    const mon = dummyMonster();
    mon.hp = 1000; mon.hpMax = 1000;
    const ctx = {
      rng: r, player: p, level: dummyLevel(),
      msg: () => {}, onMonsterKilled: () => {}, onPlayerDamaged: () => {}, onPlayerKilled: () => {},
    };
    playerRangedAttack(ctx, mon, stone, true);
    damage += 1000 - mon.hp;
  }
  assert.ok(damage > 30, `damage ${damage}`);
});
