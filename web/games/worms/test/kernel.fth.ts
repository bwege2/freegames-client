// The Forth system under Worms?, rebuilt for the test harness. Worms? was written in EA FORTH, Electronic
// Arts' own fig-FORTH for the C64, which is lost: the source disk has only the game's screens. This is a
// fig-FORTH 1.1 6502 kernel (W. F. Ragsdale's model, public domain) in the same Forth assembler syntax
// the game's CODE words use, with the few EA FORTH words the game calls (A0+, AY+, PUSH0A, 2*, ><, MSB,
// LSB, J, ROLL, JIFFYS, CALL, SETNAM, SETLFS, CLOSE, KEYMASK, DISP) as their uses in the game define
// them (re/worms/NOTES.md "EA FORTH"). It is read in HEX. Words that only the compiler needs (":",
// "IF", "CONSTANT" ...) are in eaforth.ts.
//
// Zero page: N 20-27 (N-1 = 1F), XSAVE 28, W-1 29 (holds $6C, JMP indirect), W 2A, IP 2C; data stack
// below 90 (X), return stack the 6502 stack. System variables at C000.

export const KERNEL = String.raw`
LABEL NEXT  1 # LDY, IP )Y LDA, W 1+ STA, DEY, IP )Y LDA, W STA,
  CLC, IP LDA, 2 # ADC, IP STA, CS IF, IP 1+ INC, THEN, W 1- JMP,
LABEL PUSH0A  PHA, 0 # LDA,
LABEL PUSH  DEX, DEX,
LABEL PUT  BOT 1+ STA, PLA, BOT STA, NEXT JMP,
LABEL POPTWO  INX, INX,
LABEL POP  INX, INX, NEXT JMP,
LABEL SETUP  .A ASL, N 1- STA,
  BEGIN, BOT LDA, N ,Y STA, INX, INY, N 1- CPY, 0= UNTIL, 0 # LDY, RTS,
LABEL DOCOL  IP 1+ LDA, PHA, IP LDA, PHA,
  CLC, W LDA, 2 # ADC, IP STA, TYA, W 1+ ADC, IP 1+ STA, NEXT JMP,
LABEL DOCON  2 # LDY, W )Y LDA, PHA, INY, W )Y LDA, PUSH JMP,
LABEL DOVAR  CLC, W LDA, 2 # ADC, PHA, TYA, W 1+ ADC, PUSH JMP,
LABEL BUMP  CLC, IP LDA, 2 # ADC, IP STA, CS IF, IP 1+ INC, THEN, NEXT JMP,
LABEL TRAMP  N 6 + ) JMP,
END-CODE

CODE LIT  IP )Y LDA, PHA, IP INC, 0= IF, IP 1+ INC, THEN,
  IP )Y LDA, IP INC, 0= IF, IP 1+ INC, THEN, PUSH JMP, END-CODE
CODE EXECUTE  BOT LDA, W STA, BOT 1+ LDA, W 1+ STA, INX, INX, W 1- JMP, END-CODE
CODE BRANCH  CLC, IP )Y LDA, IP ADC, PHA, INY, IP )Y LDA, IP 1+ ADC, IP 1+ STA,
  PLA, IP STA, NEXT JMP, END-CODE
CODE 0BRANCH  INX, INX, FE ,X LDA, FF ,X ORA, 0= NOT IF, BUMP JMP, THEN, ' BRANCH JMP, END-CODE
CODE (LOOP)  XSAVE STX, TSX, 101 ,X INC, 0= IF, 102 ,X INC, THEN,
LABEL PL1  CLC, 103 ,X LDA, 101 ,X SBC, 104 ,X LDA, 102 ,X SBC,
LABEL PL2  XSAVE LDX, .A ASL, CS NOT IF, ' BRANCH JMP, THEN,
  PLA, PLA, PLA, PLA, BUMP JMP, END-CODE
CODE (+LOOP)  INX, INX, XSAVE STX, FF ,X LDA, PHA, PHA, FE ,X LDA, TSX, INX, INX,
  CLC, 101 ,X ADC, 101 ,X STA, PLA, 102 ,X ADC, 102 ,X STA, PLA,
  0< NOT IF, PL1 JMP, THEN,
  CLC, 101 ,X LDA, 103 ,X SBC, 102 ,X LDA, 104 ,X SBC, PL2 JMP, END-CODE
CODE (DO)  3 ,X LDA, PHA, 2 ,X LDA, PHA, 1 ,X LDA, PHA, BOT LDA, PHA, POPTWO JMP, END-CODE
CODE I  XSAVE STX, TSX, 101 ,X LDA, PHA, 102 ,X LDA, XSAVE LDX, PUSH JMP, END-CODE
CODE R  XSAVE STX, TSX, 101 ,X LDA, PHA, 102 ,X LDA, XSAVE LDX, PUSH JMP, END-CODE
CODE J  XSAVE STX, TSX, 105 ,X LDA, PHA, 106 ,X LDA, XSAVE LDX, PUSH JMP, END-CODE
CODE LEAVE  XSAVE STX, TSX, 101 ,X LDA, 103 ,X STA, 102 ,X LDA, 104 ,X STA, XSAVE LDX, NEXT JMP, END-CODE
CODE >R  BOT 1+ LDA, PHA, BOT LDA, PHA, POP JMP, END-CODE
CODE R>  DEX, DEX, PLA, BOT STA, PLA, BOT 1+ STA, NEXT JMP, END-CODE
CODE (;S)  PLA, IP STA, PLA, IP 1+ STA, NEXT JMP, END-CODE
CODE 0=  BOT LDA, BOT 1+ ORA, BOT 1+ STY, 0= IF, INY, THEN, BOT STY, NEXT JMP, END-CODE
CODE 0<  BOT 1+ ASL, TYA, .A ROL, BOT 1+ STY, BOT STA, NEXT JMP, END-CODE
CODE +  CLC, BOT LDA, SEC ADC, SEC STA, BOT 1+ LDA, SEC 1+ ADC, SEC 1+ STA, POP JMP, END-CODE
CODE -  SEC, SEC LDA, BOT SBC, SEC STA, SEC 1+ LDA, BOT 1+ SBC, SEC 1+ STA, POP JMP, END-CODE
CODE MINUS  SEC, TYA, BOT SBC, BOT STA, TYA, BOT 1+ SBC, BOT 1+ STA, NEXT JMP, END-CODE
CODE DMINUS  SEC, TYA, SEC SBC, SEC STA, TYA, SEC 1+ SBC, SEC 1+ STA,
  TYA, BOT SBC, BOT STA, TYA, BOT 1+ SBC, BOT 1+ STA, NEXT JMP, END-CODE
CODE AND  BOT LDA, SEC AND, PHA, BOT 1+ LDA, SEC 1+ AND, INX, INX, PUT JMP, END-CODE
CODE OR  BOT LDA, SEC ORA, PHA, BOT 1+ LDA, SEC 1+ ORA, INX, INX, PUT JMP, END-CODE
CODE XOR  BOT LDA, SEC EOR, PHA, BOT 1+ LDA, SEC 1+ EOR, INX, INX, PUT JMP, END-CODE
CODE U<  SEC, SEC LDA, BOT SBC, SEC 1+ LDA, BOT 1+ SBC, SEC 1+ STY,
  CS NOT IF, INY, THEN, SEC STY, POP JMP, END-CODE
CODE <  SEC, SEC LDA, BOT SBC, SEC 1+ LDA, BOT 1+ SBC, SEC 1+ STY,
  VS IF, 80 # EOR, THEN, 0< IF, INY, THEN, SEC STY, POP JMP, END-CODE
CODE DUP  BOT LDA, PHA, BOT 1+ LDA, PUSH JMP, END-CODE
CODE DROP  POP JMP, END-CODE
CODE SWAP  SEC LDA, PHA, BOT LDA, SEC STA, SEC 1+ LDA, BOT 1+ LDY, SEC 1+ STY, PUT JMP, END-CODE
CODE OVER  SEC LDA, PHA, SEC 1+ LDA, PUSH JMP, END-CODE
CODE @  BOT X) LDA, PHA, BOT INC, 0= IF, BOT 1+ INC, THEN, BOT X) LDA, PUT JMP, END-CODE
CODE C@  BOT X) LDA, BOT STA, BOT 1+ STY, NEXT JMP, END-CODE
CODE !  SEC LDA, BOT X) STA, BOT INC, 0= IF, BOT 1+ INC, THEN, SEC 1+ LDA, BOT X) STA, POPTWO JMP, END-CODE
CODE C!  SEC LDA, BOT X) STA, POPTWO JMP, END-CODE
CODE +!  CLC, BOT X) LDA, SEC ADC, BOT X) STA, BOT INC, 0= IF, BOT 1+ INC, THEN,
  BOT X) LDA, SEC 1+ ADC, BOT X) STA, POPTWO JMP, END-CODE
CODE 1+  BOT INC, 0= IF, BOT 1+ INC, THEN, NEXT JMP, END-CODE
CODE 2+  CLC, BOT LDA, 2 # ADC, BOT STA, CS IF, BOT 1+ INC, THEN, NEXT JMP, END-CODE
CODE 1-  BOT LDA, 0= IF, BOT 1+ DEC, THEN, BOT DEC, NEXT JMP, END-CODE
CODE 2-  SEC, BOT LDA, 2 # SBC, BOT STA, CS NOT IF, BOT 1+ DEC, THEN, NEXT JMP, END-CODE
CODE 2*  BOT ASL, BOT 1+ ROL, NEXT JMP, END-CODE
CODE 2/  BOT 1+ LDA, .A ASL, BOT 1+ ROR, BOT ROR, NEXT JMP, END-CODE
CODE ><  BOT LDA, PHA, BOT 1+ LDA, BOT STA, PLA, BOT 1+ STA, NEXT JMP, END-CODE
CODE MSB  BOT 1+ LDA, BOT STA, BOT 1+ STY, NEXT JMP, END-CODE
CODE LSB  BOT 1+ STY, NEXT JMP, END-CODE
CODE NOOP  NEXT JMP, END-CODE
CODE SP@  TXA, PUSH0A JMP, END-CODE
CODE SP!  90 # LDX, NEXT JMP, END-CODE
CODE RP!  XSAVE STX, FF # LDX, TXS, XSAVE LDX, NEXT JMP, END-CODE
CODE A0+  0 # LDY,
LABEL AY+  CLC, BOT ADC, BOT STA, TYA, BOT 1+ ADC, BOT 1+ STA, 0 # LDY, RTS, END-CODE
CODE AY+  AY+ JMP, END-CODE
CODE U*  SEC LDA, N STA, SEC STY, SEC 1+ LDA, N 1+ STA, SEC 1+ STY, 10 # LDY,
  BEGIN, SEC ASL, SEC 1+ ROL, BOT ROL, BOT 1+ ROL,
    CS IF, CLC, N LDA, SEC ADC, SEC STA, N 1+ LDA, SEC 1+ ADC, SEC 1+ STA,
      0 # LDA, BOT ADC, BOT STA, 0 # LDA, BOT 1+ ADC, BOT 1+ STA, THEN,
  DEY, 0= UNTIL, NEXT JMP, END-CODE
CODE U/  4 ,X LDA, SEC LDY, 4 ,X STY, .A ASL, SEC STA,
  5 ,X LDA, SEC 1+ LDY, 5 ,X STY, .A ROL, SEC 1+ STA, 10 # LDA, N STA,
  BEGIN, 4 ,X ROL, 5 ,X ROL, SEC, 4 ,X LDA, BOT SBC, TAY, 5 ,X LDA, BOT 1+ SBC,
    CS IF, 4 ,X STY, 5 ,X STA, THEN,
    SEC ROL, SEC 1+ ROL, N DEC, 0= UNTIL, 0 # LDY, POP JMP, END-CODE
CODE CMOVE  3 # LDA, SETUP JSR,
  BEGIN, N LDA, N 1+ ORA, 0= IF, NEXT JMP, THEN,
    N 4 + )Y LDA, N 2+ )Y STA,
    N 4 + INC, 0= IF, N 5 + INC, THEN, N 2+ INC, 0= IF, N 3 + INC, THEN,
    N LDA, 0= IF, N 1+ DEC, THEN, N DEC,
  AGAIN, END-CODE
CODE FILL  3 # LDA, SETUP JSR,
  BEGIN, N 2+ LDA, N 3 + ORA, 0= IF, NEXT JMP, THEN,
    N LDA, N 4 + )Y STA,
    N 4 + INC, 0= IF, N 5 + INC, THEN,
    N 2+ LDA, 0= IF, N 3 + DEC, THEN, N 2+ DEC,
  AGAIN, END-CODE
CODE EMIT  BOT LDA, XSAVE STX, FFD2 JSR, XSAVE LDX, POP JMP, END-CODE
CODE CALL  BOT LDA, N 6 + STA, BOT 1+ LDA, N 7 + STA,
  SEC LDA, N 2+ STA, 4 ,X LDA, N 3 + STA, 6 ,X LDA, N 4 + STA,
  INX, INX, INX, INX, INX, INX, XSAVE STX,
  N 4 + LDA, N 3 + LDX, N 2+ LDY, TRAMP JSR,
  XSAVE LDX, BOT STA, 0 # LDA, .A ROL, BOT 1+ STA, NEXT JMP, END-CODE
CODE SETNAM  SEC LDA, N STA, SEC 1+ LDA, N 1+ STA, BOT LDA, N 2+ STA, XSAVE STX,
  N 2+ LDA, N LDX, N 1+ LDY, FFBD JSR, XSAVE LDX, POPTWO JMP, END-CODE
CODE SETLFS  BOT LDA, N STA, SEC LDA, N 1+ STA, 4 ,X LDA, N 2+ STA, XSAVE STX,
  N 2+ LDA, N 1+ LDX, N LDY, FFBA JSR, XSAVE LDX, INX, INX, POPTWO JMP, END-CODE
CODE CLOSE  BOT LDA, XSAVE STX, FFC3 JSR, XSAVE LDX, BOT STA, 0 # LDA, BOT 1+ STA, NEXT JMP, END-CODE

C000 CONSTANT DP  C002 CONSTANT BASE  C004 CONSTANT DISP  C008 CONSTANT KEYMASK  C00A CONSTANT FENCE
20 CONSTANT BL  90 CONSTANT S0
: HERE DP @ ;
: ALLOT DP +! ;
: , HERE ! 2 ALLOT ;
: C, HERE C! 1 ALLOT ;
: PAD HERE 44 + ;
: HEX 10 BASE ! ;
: DECIMAL 0A BASE ! ;
: ROT >R SWAP R> SWAP ;
: 2DUP OVER OVER ;
: 2DROP DROP DROP ;
: -DUP DUP IF DUP THEN ;
: = - 0= ;
: > SWAP < ;
: MAX 2DUP < IF SWAP THEN DROP ;
: MIN 2DUP > IF SWAP THEN DROP ;
: +- 0< IF MINUS THEN ;
: D+- 0< IF DMINUS THEN ;
: ABS DUP +- ;
: DABS DUP D+- ;
: S->D DUP 0< MINUS ;
: M* 2DUP XOR >R ABS SWAP ABS U* R> D+- ;
: M/ OVER >R >R DABS R ABS U/ R> R XOR +- SWAP R> +- SWAP ;
: * M* DROP ;
: /MOD >R S->D R> M/ ;
: / /MOD SWAP DROP ;
: MOD /MOD DROP ;
: BLANKS BL FILL ;
: COUNT DUP 1+ SWAP C@ ;
: TYPE -DUP IF OVER + SWAP DO I C@ EMIT LOOP ELSE DROP THEN ;
: (.") R COUNT DUP 1+ R> + >R TYPE ;
: SPACE BL EMIT ;
: PAGE 93 EMIT ;
: BELL 7 EMIT ;
: DEPTH SP@ S0 SWAP - 2/ ;
: JIFFYS 0 DO A2 C@ BEGIN A2 C@ OVER = 0= UNTIL DROP LOOP ;
: QUIT NOOP ;
`;
