// Writes src/image.ts from re/pinball/orig (run `bash re/pinball/fetch.sh` first):
//   node games/pinball/test/gen-image.ts
// The port keeps the original's memory: what each listing assembles to (code and data) is loaded at
// its address, so tables, the parts library, fonts, icons, and every byte the original reads beyond a
// table's end are the original's. The code bytes are never executed: the routines are the TypeScript
// translation in src/. image.test.ts checks that the file is what the listings assemble to.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadAll } from './apple2.ts';
import type { Assembly } from './merlin.ts';

export function segments(a: Assembly): { org: number; hex: string }[] {
  const out: { org: number; hex: string }[] = [];
  let i = 0;
  while (i < 0x10000) {
    if (!a.written[i]) {
      i++;
      continue;
    }
    const org = i;
    let hex = '';
    while (i < 0x10000 && a.written[i]) hex += a.mem[i++].toString(16).padStart(2, '0');
    out.push({ org, hex });
  }
  return out;
}

export function render(): string {
  const A = loadAll();
  const files = ['CDRAW', 'PPAK', 'RUN', 'RUN2', 'EDIT', 'WIRE', 'DISK', 'SWAP'] as const;
  let s = '// Generated by test/gen-image.ts from Bill Budge\'s listings (re/pinball/orig, MIT license): do not edit.\n';
  s += '// IMAGE: the bytes each listing assembles to, by address. SYM: the addresses of its labels.\n\n';
  s += 'export const IMAGE = {\n';
  for (const f of files) {
    s += `  ${f}: [\n`;
    for (const seg of segments(A[f])) {
      s += `    { org: 0x${seg.org.toString(16)}, hex:\n`;
      for (let i = 0; i < seg.hex.length; i += 96) s += `      '${seg.hex.slice(i, i + 96)}'${i + 96 < seg.hex.length ? ' +' : ','}\n`;
      s += '    },\n';
    }
    s += '  ],\n';
  }
  s += '};\n\nexport const SYM = {\n';
  for (const f of files) {
    s += `  ${f}: {\n`;
    // labels, and the EQUs that name a place in the file (`BITMAP EQU *+1`, `CLR EQU XOR`)
    const a = A[f];
    const syms = new Map(a.labels);
    for (const l of a.lines) {
      if (l.op === 'EQU' && l.label && l.addr >= a.org && l.addr < a.end) syms.set(l.label, l.addr);
      // RUN.S: the part bitmaps' addresses (BITMAPS, LAUNCHERB ... BALLB at $7000)
      if (f === 'RUN' && l.op === 'EQU' && l.label && l.addr >= 0x7000 && l.addr < 0x7700) syms.set(l.label, l.addr);
    }
    const entries = [...syms.entries()].sort((a, b) => a[1] - b[1] || a[0].localeCompare(b[0]));
    for (const [k, v] of entries) s += `    ${k}: 0x${v.toString(16)},\n`;
    s += '  },\n';
  }
  s += '} as const;\n';
  return s;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(import.meta.dirname, '../src/image.ts'), render());
}
